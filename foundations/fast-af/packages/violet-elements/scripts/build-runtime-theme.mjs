import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const packageRoot = path.resolve(__dirname, "..");
// The built-in default theme set is AFD's default, shared with Loam: a committed export of Loam's
// Violet themes (D50; endpoints/loam/docs/phases/0-kernel-chrome/spec.md, section 2.4), which
// `pnpm -F @lushly-dev/loam-theme theme:export-components` writes and `theme:check` compares. The
// components' token interface, tokens/interface.json, belongs to this package: the export must
// supply every id it lists, in every preset. The light preset is the default (D38). A product with
// its own tree installs its own set with installVioletThemeSet(), and this one is not installed.
const exportPath = path.join(packageRoot, "tokens", "violet-theme.export.json");
const interfacePath = path.join(packageRoot, "tokens", "interface.json");
const outputPath = path.join(
  packageRoot,
  "src",
  "theme",
  "generated",
  "violet-theme.generated.ts",
);
// The preset names alone, so the runtime knows them without loading the built-in set's values.
const presetsOutputPath = path.join(path.dirname(outputPath), "violet-theme-presets.generated.ts");
const defaultPreset = "light";

function readPresets(themeExport, tokenInterface) {
  if (themeExport?.contractVersion !== 1) {
    throw new Error(`${exportPath}: expected contractVersion 1, got ${themeExport?.contractVersion}`);
  }

  const presets = themeExport.presets ?? {};
  const defaultIds = (presets[defaultPreset] ?? []).map(token => token.id).join(",");

  if (defaultIds === "") {
    throw new Error(`${exportPath}: the ${defaultPreset} preset is missing or empty`);
  }

  const interfaceIds = Object.keys(tokenInterface?.tokens ?? {});
  if (interfaceIds.length === 0) {
    throw new Error(`${interfacePath}: no tokens`);
  }

  for (const [presetName, tokens] of Object.entries(presets)) {
    const ids = tokens.map(token => token.id);
    if (ids.join(",") !== defaultIds) {
      throw new Error(`${exportPath}: the ${presetName} preset does not have the ${defaultPreset} preset's ids`);
    }
    const missing = interfaceIds.filter(id => !ids.includes(id));
    if (missing.length > 0) {
      throw new Error(
        `${exportPath}: the ${presetName} preset lacks interface ids ${missing.join(", ")}; run \`pnpm -F @lushly-dev/loam-theme theme:export-components\` after Loam's tree supplies them`,
      );
    }
  }

  return presets;
}

async function main() {
  const presets = readPresets(
    JSON.parse(await readFile(exportPath, "utf8")),
    JSON.parse(await readFile(interfacePath, "utf8")),
  );
  const presetNames = Object.keys(presets);
  // One token per line keeps the module small and its diffs readable.
  const presetSource = Object.entries(presets)
    .map(([name, tokens]) => {
      const lines = tokens.map(
        ({ id, value }) => `      { id: ${JSON.stringify(id)}, value: ${JSON.stringify(value)} },`,
      );
      return [`    ${JSON.stringify(name)}: [`, ...lines, "    ],"].join("\n");
    })
    .join("\n");

  const header = `/**
 * Auto-generated by scripts/build-runtime-theme.mjs from tokens/violet-theme.export.json.
 * Do not edit this file directly.
 */
`;
  const source = `${header}
import type { VioletThemeSet } from "../violet-theme-css";

/** The built-in default theme set, installed when a product installs none of its own. */
export const violetThemeBuiltInSet = {
  defaultPreset: ${JSON.stringify(defaultPreset)},
  presets: {
${presetSource}
  },
} as const satisfies VioletThemeSet;
`;
  const presetsSource = `${header}
/** The built-in default set's default preset. */
export const VIOLET_THEME_DEFAULT_PRESET = ${JSON.stringify(defaultPreset)};

/** The built-in default set's presets. */
export const violetThemePresets = [${presetNames.map(name => JSON.stringify(name)).join(", ")}] as const;

export type VioletBuiltInThemePreset = (typeof violetThemePresets)[number];
`;

  await mkdir(path.dirname(outputPath), { recursive: true });
  await writeFile(outputPath, source, "utf8");
  await writeFile(presetsOutputPath, presetsSource, "utf8");
}

main().catch(error => {
  console.error(error);
  process.exitCode = 1;
});
