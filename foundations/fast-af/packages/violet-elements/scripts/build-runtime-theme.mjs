import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const packageRoot = path.resolve(__dirname, "..");
// The presets come from Loam's Violet themes, as a committed export of the component ids per theme
// (D50; endpoints/loam/docs/phases/0-kernel-chrome/spec.md, section 2.4). Loam's theme package
// writes it with `pnpm -F @lushly-dev/loam-theme theme:export-components` and checks it in
// `theme:check`. The light preset is the baked-in default (D38).
const exportPath = path.join(packageRoot, "tokens", "violet-theme.export.json");
const outputPath = path.join(
  packageRoot,
  "src",
  "theme",
  "generated",
  "violet-theme.generated.ts",
);
const defaultPreset = "light";

function tokenIdToCssVar(tokenId) {
  return `--${tokenId.replace(/\./g, "-")}`;
}

function buildDeclarations(tokens) {
  return tokens.map(token => `  ${tokenIdToCssVar(token.id)}: ${token.value};`).join("\n");
}

function readPresets(themeExport) {
  if (themeExport?.contractVersion !== 1) {
    throw new Error(`${exportPath}: expected contractVersion 1, got ${themeExport?.contractVersion}`);
  }

  const presets = themeExport.presets ?? {};
  const defaultIds = (presets[defaultPreset] ?? []).map(token => token.id).join(",");

  if (defaultIds === "") {
    throw new Error(`${exportPath}: the ${defaultPreset} preset is missing or empty`);
  }

  for (const [presetName, tokens] of Object.entries(presets)) {
    if (tokens.map(token => token.id).join(",") !== defaultIds) {
      throw new Error(`${exportPath}: the ${presetName} preset does not have the ${defaultPreset} preset's ids`);
    }
  }

  return presets;
}

async function main() {
  const presets = readPresets(JSON.parse(await readFile(exportPath, "utf8")));
  const presetDeclarations = Object.fromEntries(
    Object.entries(presets).map(([presetName, tokens]) => [presetName, buildDeclarations(tokens)]),
  );
  const presetNames = Object.keys(presetDeclarations);
  const themeCssBlocks = [
    ":root,",
    "[data-violet-theme-root]",
    "{",
    presetDeclarations[defaultPreset],
    "}",
  ];

  for (const presetName of presetNames) {
    if (presetName === defaultPreset) {
      continue;
    }

    themeCssBlocks.push(
      `:root[data-violet-theme="${presetName}"],`,
      `[data-violet-theme-root][data-violet-theme="${presetName}"]`,
      "{",
      presetDeclarations[presetName],
      "}",
    );
  }

  const themeCssText = themeCssBlocks.join("\n");

  const source = `/**
 * Auto-generated by scripts/build-runtime-theme.mjs.
 * Do not edit this file directly.
 */

export const VIOLET_THEME_ROOT_ATTRIBUTE = "data-violet-theme-root";
export const VIOLET_THEME_PRESET_ATTRIBUTE = "data-violet-theme";
export const VIOLET_THEME_DEFAULT_PRESET = ${JSON.stringify(defaultPreset)};

export const violetThemeDeclarationsByPreset = ${JSON.stringify(presetDeclarations, null, 2)} as const;
export type VioletThemePreset = keyof typeof violetThemeDeclarationsByPreset;
export const violetThemePresets = Object.keys(violetThemeDeclarationsByPreset) as VioletThemePreset[];

export const violetThemeDeclarations = violetThemeDeclarationsByPreset[VIOLET_THEME_DEFAULT_PRESET];
export const violetThemeCssText = ${JSON.stringify(themeCssText)};

export function isVioletThemePreset(value: string | null | undefined): value is VioletThemePreset {
  return typeof value === "string" && (violetThemePresets as readonly string[]).includes(value);
}

export function normalizeVioletThemePreset(value: string | null | undefined): VioletThemePreset {
  return isVioletThemePreset(value) ? value : VIOLET_THEME_DEFAULT_PRESET;
}

function isShadowRoot(target: unknown): target is ShadowRoot {
  return typeof ShadowRoot !== "undefined" && target instanceof ShadowRoot;
}

function isDocument(target: unknown): target is Document {
  return typeof Document !== "undefined" && target instanceof Document;
}

function resolveStyleContainer(target: Document | ShadowRoot = document): ShadowRoot | HTMLElement {
  if (isShadowRoot(target)) {
    return target;
  }

  if (isDocument(target)) {
    return target.head ?? target.documentElement;
  }

  return document.head ?? document.documentElement;
}

function resolvePresetTarget(target: Document | HTMLElement = document): HTMLElement {
  if (isDocument(target)) {
    return target.documentElement;
  }

  return target;
}

export function installVioletTheme(target: Document | ShadowRoot = document): HTMLStyleElement {
  const styleContainer = resolveStyleContainer(target);
  const existing = styleContainer.querySelector('style[data-violet-theme="runtime"]');

  if (existing instanceof HTMLStyleElement) {
    existing.textContent = violetThemeCssText;
    return existing;
  }

  const style = document.createElement("style");
  style.dataset.violetTheme = "runtime";
  style.textContent = violetThemeCssText;
  styleContainer.append(style);
  return style;
}

export function applyVioletThemePreset<T extends Document | HTMLElement>(
  target: T,
  preset: VioletThemePreset = VIOLET_THEME_DEFAULT_PRESET,
): T {
  const resolvedPreset = normalizeVioletThemePreset(preset);
  resolvePresetTarget(target).setAttribute(VIOLET_THEME_PRESET_ATTRIBUTE, resolvedPreset);
  return target;
}

export function getVioletThemePreset(target: Document | HTMLElement = document): VioletThemePreset {
  return normalizeVioletThemePreset(resolvePresetTarget(target).getAttribute(VIOLET_THEME_PRESET_ATTRIBUTE));
}

export function applyVioletThemeRoot<T extends HTMLElement>(
  element: T,
  preset: VioletThemePreset = VIOLET_THEME_DEFAULT_PRESET,
): T {
  element.setAttribute(VIOLET_THEME_ROOT_ATTRIBUTE, "");
  applyVioletThemePreset(element, preset);
  return element;
}
`;

  await mkdir(path.dirname(outputPath), { recursive: true });
  await writeFile(outputPath, source, "utf8");
}

main().catch(error => {
  console.error(error);
  process.exitCode = 1;
});
