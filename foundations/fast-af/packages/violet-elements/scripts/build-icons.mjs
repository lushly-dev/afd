import { mkdir, readdir, readFile, rm, stat, writeFile } from "node:fs/promises";
import { resolve } from "node:path";

const packageRoot = process.cwd();
const sourcesRoot = resolve(packageRoot, "icons", "sources");
const generatedRoot = resolve(packageRoot, "src", "icon", "generated");
const generatedIconsRoot = resolve(generatedRoot, "icons");

function toIconName(sourceId, fileName) {
  return `${sourceId}/${fileName.replace(/\.svg$/u, "")}`;
}

function toModuleName(sourceId, fileName) {
  return `${sourceId}-${fileName.replace(/\.svg$/u, "")}`;
}

function toPascalCase(value) {
  return value
    .split(/[^a-zA-Z0-9]+/u)
    .filter(Boolean)
    .map((segment) => segment[0].toUpperCase() + segment.slice(1))
    .join("");
}

function normalizeSvg(svg) {
  return svg
    .replace(/\r\n/gu, "\n")
    .replace(/>\s+</gu, "><")
    .replace(/\n+/gu, " ")
    .replace(/\s{2,}/gu, " ")
    .trim();
}

/** Code-point order, so the generated files do not depend on the machine's locale. */
function byCodePoint(a, b) {
  return a < b ? -1 : a > b ? 1 : 0;
}

/** Whether a file exists; any error other than "not found" is thrown. */
async function exists(path) {
  try {
    await stat(path);
    return true;
  } catch (error) {
    if (error.code === "ENOENT") return false;
    throw error;
  }
}

/**
 * A source's SVGs, one per icon, sorted by name. A set drawn with an icon kit (an
 * `iconset.json` beside `source.json`) keeps each icon in `icons/<name>/` beside its
 * `icon.json`, and the build takes its default drawing. An imported set keeps flat
 * files in `raw/`.
 */
async function sourceFiles(sourceId, sourceDir) {
  const specPath = resolve(sourceDir, "iconset.json");
  if (!(await exists(specPath))) {
    const rawDir = resolve(sourceDir, "raw");
    return (await readdir(rawDir, { withFileTypes: true }))
      .filter((entry) => entry.isFile() && entry.name.endsWith(".svg"))
      .map((entry) => ({ file: entry.name, path: resolve(rawDir, entry.name) }))
      .sort((a, b) => byCodePoint(a.file, b.file));
  }
  const spec = JSON.parse(await readFile(specPath, "utf8"));
  if (!Number.isInteger(spec?.defaultSize)) {
    throw new Error(`${sourceId}: iconset.json needs an integer defaultSize to choose each icon's drawing.`);
  }
  const drawing = `${spec.defaultVariant ?? "outline"}-${spec.defaultSize}.svg`;
  const iconsDir = resolve(sourceDir, "icons");
  const files = [];
  for (const entry of await readdir(iconsDir, { withFileTypes: true })) {
    if (!entry.isDirectory() || !(await exists(resolve(iconsDir, entry.name, "icon.json")))) continue;
    const path = resolve(iconsDir, entry.name, drawing);
    if (!(await exists(path))) {
      throw new Error(`${sourceId}/${entry.name}: the icon has no ${drawing}, its default drawing. Save one, or remove the icon's folder.`);
    }
    files.push({ file: `${entry.name}.svg`, path });
  }
  return files.sort((a, b) => byCodePoint(a.file, b.file));
}

// Read every source before touching the generated folder, so a bad source leaves it as it was.
const sourceIds = (await readdir(sourcesRoot, { withFileTypes: true }))
  .filter((entry) => entry.isDirectory())
  .map((entry) => entry.name)
  .sort(byCodePoint);

const icons = [];
const sources = [];

for (const sourceId of sourceIds) {
  const sourceDir = resolve(sourcesRoot, sourceId);
  const source = JSON.parse(await readFile(resolve(sourceDir, "source.json"), "utf8"));
  sources.push(source);

  for (const { file, path } of await sourceFiles(sourceId, sourceDir)) {
    const svg = await readFile(path, "utf8");
    icons.push({
      name: toIconName(sourceId, file),
      sourceId,
      originalFile: file,
      moduleName: toModuleName(sourceId, file),
      exportStem: toPascalCase(toModuleName(sourceId, file)),
      svg: normalizeSvg(svg),
    });
  }
}

await rm(generatedRoot, { recursive: true, force: true });
await mkdir(generatedIconsRoot, { recursive: true });

const sourceLines = [
  "/*",
  " * Auto-generated by scripts/build-icons.mjs.",
  " * Do not edit directly.",
  " */",
  "",
  'import type { VioletIconSource } from "../icon-registry";',
  "",
  `export const violetIconSources = ${JSON.stringify(sources, null, 2)} as const satisfies readonly VioletIconSource[];`,
  "",
  'export type VioletIconSourceId = (typeof violetIconSources)[number]["id"];',
  "",
];

await writeFile(resolve(generatedRoot, "icon-sources.ts"), sourceLines.join("\n"));

const indexLines = [
  "/*",
  " * Auto-generated by scripts/build-icons.mjs.",
  " * Do not edit directly.",
  " */",
  "",
  'export * from "./icon-sources";',
];

for (const icon of icons) {
  const definitionName = `${icon.exportStem[0].toLowerCase()}${icon.exportStem.slice(1)}Icon`;
  const fileLines = [
    "/*",
    " * Auto-generated by scripts/build-icons.mjs.",
    " * Do not edit directly.",
    " */",
    "",
    'import { registerVioletIcon } from "../../icon-registry";',
    'import type { VioletIconDefinition } from "../../icon-registry";',
    "",
    `export const ${definitionName} = ${JSON.stringify(
      {
        name: icon.name,
        sourceId: icon.sourceId,
        originalFile: icon.originalFile,
        svg: icon.svg,
      },
      null,
      2,
    )} as const satisfies VioletIconDefinition;`,
    "",
    `export function register${icon.exportStem}Icon(): VioletIconDefinition {`,
    `  return registerVioletIcon(${definitionName});`,
    "}",
    "",
  ];

  await writeFile(resolve(generatedIconsRoot, `${icon.moduleName}.ts`), fileLines.join("\n"));
  indexLines.push(`export * from "./icons/${icon.moduleName}";`);
}

indexLines.push("");
await writeFile(resolve(generatedRoot, "index.ts"), indexLines.join("\n"));
