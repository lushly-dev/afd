import { mkdir, readdir, readFile, rm, writeFile } from "node:fs/promises";
import { resolve } from "node:path";

const packageRoot = process.cwd();
const sourcesRoot = resolve(packageRoot, "icons", "sources");
const generatedRoot = resolve(packageRoot, "src", "icon", "generated");
const generatedIconsRoot = resolve(generatedRoot, "icons");

function toIconName(sourceId, fileName) {
  return `${sourceId}/${fileName.replace(/\.svg$/u, "")}`;
}

function toModuleName(sourceId, fileName) {
  return `${sourceId}-${fileName.replace(/\.svg$/u, "")}`;
}

function toPascalCase(value) {
  return value
    .split(/[^a-zA-Z0-9]+/u)
    .filter(Boolean)
    .map((segment) => segment[0].toUpperCase() + segment.slice(1))
    .join("");
}

function normalizeSvg(svg) {
  return svg
    .replace(/\r\n/gu, "\n")
    .replace(/>\s+</gu, "><")
    .replace(/\n+/gu, " ")
    .replace(/\s{2,}/gu, " ")
    .trim();
}

await rm(generatedRoot, { recursive: true, force: true });
await mkdir(generatedIconsRoot, { recursive: true });

const sourceIds = (await readdir(sourcesRoot, { withFileTypes: true }))
  .filter((entry) => entry.isDirectory())
  .map((entry) => entry.name)
  .sort((a, b) => a.localeCompare(b));

const icons = [];
const sources = [];

for (const sourceId of sourceIds) {
  const sourceDir = resolve(sourcesRoot, sourceId);
  const source = JSON.parse(await readFile(resolve(sourceDir, "source.json"), "utf8"));
  sources.push(source);

  const rawDir = resolve(sourceDir, "raw");
  const files = (await readdir(rawDir, { withFileTypes: true }))
    .filter((entry) => entry.isFile() && entry.name.endsWith(".svg"))
    .map((entry) => entry.name)
    .sort((a, b) => a.localeCompare(b));

  for (const file of files) {
    const svg = await readFile(resolve(rawDir, file), "utf8");
    icons.push({
      name: toIconName(sourceId, file),
      sourceId,
      originalFile: file,
      moduleName: toModuleName(sourceId, file),
      exportStem: toPascalCase(toModuleName(sourceId, file)),
      svg: normalizeSvg(svg),
    });
  }
}

const sourceLines = [
  "/*",
  " * Auto-generated by scripts/build-icons.mjs.",
  " * Do not edit directly.",
  " */",
  "",
  'import type { VioletIconSource } from "../icon-registry";',
  "",
  `export const violetIconSources = ${JSON.stringify(sources, null, 2)} as const satisfies readonly VioletIconSource[];`,
  "",
  'export type VioletIconSourceId = (typeof violetIconSources)[number]["id"];',
  "",
];

await writeFile(resolve(generatedRoot, "icon-sources.ts"), sourceLines.join("\n"));

const indexLines = [
  "/*",
  " * Auto-generated by scripts/build-icons.mjs.",
  " * Do not edit directly.",
  " */",
  "",
  'export * from "./icon-sources";',
];

for (const icon of icons) {
  const definitionName = `${icon.exportStem[0].toLowerCase()}${icon.exportStem.slice(1)}Icon`;
  const fileLines = [
    "/*",
    " * Auto-generated by scripts/build-icons.mjs.",
    " * Do not edit directly.",
    " */",
    "",
    'import { registerVioletIcon } from "../../icon-registry";',
    'import type { VioletIconDefinition } from "../../icon-registry";',
    "",
    `export const ${definitionName} = ${JSON.stringify(
      {
        name: icon.name,
        sourceId: icon.sourceId,
        originalFile: icon.originalFile,
        svg: icon.svg,
      },
      null,
      2,
    )} as const satisfies VioletIconDefinition;`,
    "",
    `export function register${icon.exportStem}Icon(): VioletIconDefinition {`,
    `  return registerVioletIcon(${definitionName});`,
    "}",
    "",
  ];

  await writeFile(resolve(generatedIconsRoot, `${icon.moduleName}.ts`), fileLines.join("\n"));
  indexLines.push(`export * from "./icons/${icon.moduleName}";`);
}

indexLines.push("");
await writeFile(resolve(generatedRoot, "index.ts"), indexLines.join("\n"));
