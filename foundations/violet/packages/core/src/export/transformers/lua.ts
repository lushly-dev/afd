import { parseColor } from '../../constraints/validators.js';
import type { ResolvedToken } from '../../types/token.js';
import type { TransformOptions, Transformer } from '../transformer.js';
import { buildNestedTokenObject, tokenIdToCamel } from '../transformer.js';

/**
 * Lua Transformer
 *
 * Exports tokens as a Lua module for WoW addons using FenUI:
 * - `colors`: color tokens as `{ r, g, b, a }` (0-1), ready to merge into `FenUI.Tokens.colors`
 * - `tokens`: every other token, nested by ID segment
 * - `theme` (when `themeMap` is set): a `FenUI:RegisterTheme` config mapping FenUI
 *   semantic names to the primitive names in `colors`
 *
 * Primitive names are the camelCased token ID without its leading `color.` segment,
 * after `prefix` (e.g. prefix 'vintageDark' + 'color.surface.canvas' -> 'vintageDarkSurfaceCanvas'),
 * so several themes can share `FenUI.Tokens.colors`.
 */
export const luaTransformer: Transformer = {
	format: 'lua',
	fileExtension: 'lua',
	name: 'Lua (FenUI)',

	transform(tokens: ResolvedToken[], options: TransformOptions = {}): string {
		const { prefix = '', includeComments = true, themeMap } = options;
		const moduleName = options.className || 'DesignTokens';
		if (!isLuaIdentifier(moduleName)) {
			throw new Error(`Lua module name '${moduleName}' is not a valid Lua identifier`);
		}

		const colorNames = new Map<string, string>(); // token ID -> primitive name
		const colorLines: string[] = [];
		const otherTokens: ResolvedToken[] = [];

		for (const token of tokens) {
			const rgba = toRgba(token.resolvedValue);
			if (!rgba) {
				otherTokens.push(token);
				continue;
			}

			const name = primitiveName(prefix, token.id);
			colorNames.set(token.id, name);
			const comment = includeComments ? ` -- ${token.resolvedValue} ${token.id}` : '';
			colorLines.push(`\t${luaKey(name)} = { ${rgba.map(formatNumber).join(', ')} },${comment}`);
		}

		const lines: string[] = [
			'-- Generated by Violet Design',
			'-- Do not edit manually',
			'',
			'local _, ns = ...',
			'',
			`local ${moduleName} = {}`,
			'',
			'-- Color primitives { r, g, b, a } in 0-1. Merge into FenUI.Tokens.colors:',
			`--   for name, rgba in pairs(${moduleName}.colors) do FenUI.Tokens.colors[name] = rgba end`,
			`${moduleName}.colors = {`,
			...colorLines,
			'}',
			'',
			'-- Non-color tokens, nested by token ID segment',
			`${moduleName}.tokens = ${toLua(
				buildNestedTokenObject(otherTokens, (token) => token.finalValue ?? token.value),
				0,
			)}`,
		];

		if (themeMap) {
			const mappings = Object.entries(themeMap).map(([semantic, tokenId]) => {
				const name = colorNames.get(tokenId);
				if (!name) {
					throw new Error(
						`themeMap maps '${semantic}' to '${tokenId}', which is not a color token in this export`,
					);
				}
				return `\t\t${luaKey(semantic)} = ${luaString(name)},`;
			});

			lines.push(
				'',
				'-- FenUI theme config: semantic token -> primitive name in colors',
				`--   FenUI:RegisterTheme(${luaString(moduleName)}, ${moduleName}.theme)`,
				`${moduleName}.theme = {`,
				`\tname = ${luaString(moduleName)},`,
				'\ttokens = {',
				...mappings,
				'\t},',
				'}',
			);
		}

		lines.push(
			'',
			'if type(ns) == "table" then',
			`\tns.${moduleName} = ${moduleName}`,
			'end',
			'',
			`return ${moduleName}`,
			'',
		);

		return lines.join('\n');
	},
};

/**
 * 'vintageDark' + 'color.surface.canvas' -> 'vintageDarkSurfaceCanvas'
 */
function primitiveName(prefix: string, tokenId: string): string {
	const id = tokenId.replace(/^color\./, '');
	const name = tokenIdToCamel(prefix ? `${prefix}.${id}` : id);
	return name.replace(/-([a-zA-Z0-9])/g, (_, c: string) => c.toUpperCase());
}

/**
 * Parse a CSS color to `[r, g, b, a]` in 0-1, or null if the value isn't a color
 */
function toRgba(value: unknown): [number, number, number, number] | null {
	if (typeof value !== 'string') return null;
	const rgb = parseColor(value);
	if (!rgb) return null;
	return [rgb.r / 255, rgb.g / 255, rgb.b / 255, parseAlpha(value.trim())];
}

/**
 * Alpha channel of a color parseColor accepted (it ignores alpha)
 */
function parseAlpha(value: string): number {
	const hex = value.match(/^#([0-9A-Fa-f]{4}|[0-9A-Fa-f]{8})$/);
	if (hex) {
		const digits = hex[1].length === 4 ? hex[1][3].repeat(2) : hex[1].slice(6);
		return Number.parseInt(digits, 16) / 255;
	}

	// rgba()/hsla(): alpha is a 4th argument, after ',' or '/'
	const args = value.slice(value.indexOf('(') + 1, value.lastIndexOf(')')).split(/[\s,/]+/);
	const alpha = args.filter(Boolean)[3];
	if (alpha === undefined) return 1;
	const parsed = Number.parseFloat(alpha);
	const normalized = alpha.endsWith('%') ? parsed / 100 : parsed;
	return Math.min(1, Math.max(0, normalized));
}

function formatNumber(n: number): string {
	return String(Number(n.toFixed(3)));
}

function isLuaIdentifier(key: string): boolean {
	return /^[A-Za-z_][A-Za-z0-9_]*$/.test(key) && !LUA_KEYWORDS.has(key);
}

function luaKey(key: string): string {
	return isLuaIdentifier(key) ? key : `[${luaString(key)}]`;
}

function luaString(value: string): string {
	return `"${value
		.replace(/\\/g, '\\\\')
		.replace(/"/g, '\\"')
		.replace(/\n/g, '\\n')
		.replace(/\r/g, '\\r')}"`;
}

/**
 * Serialize a JSON-like value to a Lua literal
 */
function toLua(value: unknown, depth: number): string {
	if (typeof value === 'string') return luaString(value);
	if (typeof value === 'number') return Number.isFinite(value) ? String(value) : 'nil';
	if (typeof value === 'boolean') return String(value);
	if (value === null || value === undefined) return 'nil';

	const indent = '\t'.repeat(depth + 1);
	const closing = '\t'.repeat(depth);
	const entries = Array.isArray(value)
		? value.map((item) => `${indent}${toLua(item, depth + 1)},`)
		: Object.entries(value as Record<string, unknown>).map(
				([key, item]) => `${indent}${luaKey(key)} = ${toLua(item, depth + 1)},`,
			);
	return entries.length === 0 ? '{}' : `{\n${entries.join('\n')}\n${closing}}`;
}

const LUA_KEYWORDS = new Set([
	'and',
	'break',
	'do',
	'else',
	'elseif',
	'end',
	'false',
	'for',
	'function',
	'goto',
	'if',
	'in',
	'local',
	'nil',
	'not',
	'or',
	'repeat',
	'return',
	'then',
	'true',
	'until',
	'while',
]);
