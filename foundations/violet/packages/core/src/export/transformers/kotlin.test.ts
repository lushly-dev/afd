import { describe, expect, it } from 'vitest';
import type { ResolvedToken } from '../../types/token.js';
import { kotlinTransformer } from './kotlin.js';

const token = (id: string, value: string | number, description?: string): ResolvedToken => ({
	id,
	value,
	resolvedValue: value,
	metadata: {
		category: 'custom',
		tier: 'semantic',
		status: 'stable',
		platforms: [],
		tags: [],
		...(description ? { description } : {}),
	},
	resolvedAt: 'test',
	inheritanceChain: ['test'],
});

const kotlinValue = (kotlin: string, name: string) =>
	kotlin
		.split('\n')
		.find((line) => line.trim().startsWith(`val ${name} =`))
		?.split(' = ')[1];

describe('kotlin transformer', () => {
	it('emits a Compose object in the default package with its imports', () => {
		const kotlin = kotlinTransformer.transform([token('color.primary', '#0078D4')]);

		expect(kotlin).toMatch(/^\/\/ VioletTokens\.kt\n\/\/ Generated by Violet Design\n/);
		expect(kotlin).toContain('package com.violet.tokens\n');
		expect(kotlin).toContain('import androidx.compose.ui.graphics.Color');
		expect(kotlin).toContain('import androidx.compose.ui.unit.dp');
		expect(kotlin).toContain('import androidx.compose.ui.unit.sp');
		expect(kotlin).toContain('object VioletTokens {');
		expect(kotlin.endsWith('}')).toBe(true);
	});

	it('uses packageName and className', () => {
		const kotlin = kotlinTransformer.transform([token('spacing.md', 16)], {
			packageName: 'com.example.brand',
			className: 'BrandTokens',
		});

		expect(kotlin).toContain('// BrandTokens.kt');
		expect(kotlin).toContain('package com.example.brand');
		expect(kotlin).toContain('object BrandTokens {');
	});

	it('nests a plural object per category and a PascalCase object per subcategory', () => {
		const kotlin = kotlinTransformer.transform([
			token('color.brand-accent.primary', '#0078D4'),
			token('color.white', '#FFFFFF'),
		]);

		expect(kotlin).toContain(
			'    // Color\n    object Colors {\n        object BrandAccent {\n            val Primary = Color(0xFF0078D4)\n        }\n        val White = Color(0xFFFFFFFF)\n    }',
		);
	});

	it('expands three-digit hex colors and upper-cases them', () => {
		const kotlin = kotlinTransformer.transform([
			token('color.short', '#fa0'),
			token('border.focus', '#abcdef'),
		]);

		expect(kotlinValue(kotlin, 'Short')).toBe('Color(0xFFFFAA00)');
		// A hex value outside the color category is still a color.
		expect(kotlinValue(kotlin, 'Focus')).toBe('Color(0xFFABCDEF)');
	});

	it('moves the alpha of eight-digit CSS hex to the front of the ARGB literal', () => {
		const kotlin = kotlinTransformer.transform([
			token('color.gold-overlay', '#FFD70080'),
			token('color.scrim', '#00000033'),
			token('color.opaque', '#0078d4ff'),
		]);

		expect(kotlinValue(kotlin, 'GoldOverlay')).toBe('Color(0x80FFD700)');
		expect(kotlinValue(kotlin, 'Scrim')).toBe('Color(0x33000000)');
		expect(kotlinValue(kotlin, 'Opaque')).toBe('Color(0xFF0078D4)');
	});

	it('converts dimensions to dp, sp for font-like names, with a 16px rem base', () => {
		const kotlin = kotlinTransformer.transform([
			token('spacing.px', '12px'),
			token('spacing.rem', '1.5rem'),
			token('typography.body-size', '14sp'),
			token('spacing.bare', '8'),
			token('font.size.body', '14'),
			token('text.size.caption', '12'),
			token('spacing.number', 4),
		]);

		expect(kotlinValue(kotlin, 'Px')).toBe('12.dp');
		expect(kotlinValue(kotlin, 'Rem')).toBe('24.dp');
		expect(kotlinValue(kotlin, 'BodySize')).toBe('14.sp');
		expect(kotlinValue(kotlin, 'Bare')).toBe('8.dp');
		expect(kotlinValue(kotlin, 'Body')).toBe('14.sp');
		expect(kotlinValue(kotlin, 'Caption')).toBe('12.sp');
		expect(kotlinValue(kotlin, 'Number')).toBe('4.dp');
	});

	it('emits other values as strings', () => {
		const kotlin = kotlinTransformer.transform([token('motion.easing', 'ease-in-out')]);

		expect(kotlinValue(kotlin, 'Easing')).toBe('"ease-in-out"');
	});

	it('escapes quotes, backslashes, template dollars and control characters in strings', () => {
		const kotlin = kotlinTransformer.transform([
			token('font.family', '"Segoe UI", sans-serif'),
			token('content.path', 'icons\\$name'),
			token('content.lines', 'one\ntwo\tthree'),
		]);

		expect(kotlinValue(kotlin, 'Family')).toBe('"\\"Segoe UI\\", sans-serif"');
		expect(kotlinValue(kotlin, 'Path')).toBe('"icons\\\\\\$name"');
		expect(kotlinValue(kotlin, 'Lines')).toBe('"one\\ntwo\\tthree"');
	});

	it('writes category headings and KDoc descriptions unless includeComments is false', () => {
		const tokens = [token('spacing.md', 16, 'Default gap')];

		const withComments = kotlinTransformer.transform(tokens);
		expect(withComments).toContain('    // Spacing\n    object Spacings {');
		expect(withComments).toContain('        /** Default gap */\n        val Md = 16.dp');

		const without = kotlinTransformer.transform(tokens, { includeComments: false });
		expect(without).not.toContain('// Spacing');
		expect(without).not.toContain('Default gap');
		expect(without).toContain('    object Spacings {\n        val Md = 16.dp');
	});
});
