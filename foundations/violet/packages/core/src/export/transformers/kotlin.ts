import type { ResolvedToken } from '../../types/token.js';
import type { TransformOptions, Transformer } from '../transformer.js';
import { groupByCategory } from '../transformer.js';

/**
 * Kotlin Transformer
 *
 * Exports tokens as Kotlin object compatible with Jetpack Compose.
 */
export const kotlinTransformer: Transformer = {
	format: 'kotlin',
	fileExtension: 'kt',
	name: 'Kotlin (Jetpack Compose)',

	transform(tokens: ResolvedToken[], options: TransformOptions = {}): string {
		const { includeComments = true } = options;

		// Use kotlin-specific options
		const packageName = (options as KotlinOptions).packageName || 'com.violet.tokens';
		const objectName = (options as KotlinOptions).className || 'VioletTokens';

		const lines: string[] = [];

		// Header
		lines.push(`// ${objectName}.kt`);
		lines.push('// Generated by Violet Design');
		lines.push('// Do not edit manually');
		lines.push(`// Generated: ${new Date().toISOString()}`);
		lines.push('');
		lines.push(`package ${packageName}`);
		lines.push('');
		lines.push('import androidx.compose.ui.graphics.Color');
		lines.push('import androidx.compose.ui.unit.dp');
		lines.push('import androidx.compose.ui.unit.sp');
		lines.push('');
		lines.push(`object ${objectName} {`);

		// Group tokens by category
		const groups = groupByCategory(tokens);

		for (const [category, categoryTokens] of groups) {
			lines.push('');

			if (includeComments) {
				lines.push(`    // ${capitalize(category)}`);
			}

			lines.push(`    object ${capitalize(category)}s {`);

			// Group by subcategory
			const subGroups = groupBySubcategory(categoryTokens);

			for (const [subcategory, subTokens] of subGroups) {
				if (subcategory !== '_root') {
					lines.push(`        object ${toPascalCase(subcategory)} {`);
				}

				for (const token of subTokens) {
					const kotlinValue = toKotlinValue(token);
					const propName = toPascalCase(getPropertyName(token.id));
					const indent = subcategory !== '_root' ? '            ' : '        ';

					if (includeComments && token.metadata?.description) {
						lines.push(`${indent}/** ${token.metadata.description} */`);
					}

					lines.push(`${indent}val ${propName} = ${kotlinValue}`);
				}

				if (subcategory !== '_root') {
					lines.push('        }');
				}
			}

			lines.push('    }');
		}

		lines.push('}');

		return lines.join('\n');
	},
};

/**
 * Kotlin-specific options
 */
interface KotlinOptions extends TransformOptions {
	className?: string;
	packageName?: string;
}

/**
 * Group tokens by subcategory (second segment of ID)
 */
function groupBySubcategory(tokens: ResolvedToken[]): Map<string, ResolvedToken[]> {
	const groups = new Map<string, ResolvedToken[]>();

	for (const token of tokens) {
		const parts = token.id.split('.');
		const subcategory = parts.length > 2 ? parts[1] : '_root';

		if (!groups.has(subcategory)) {
			groups.set(subcategory, []);
		}
		groups.get(subcategory)?.push(token);
	}

	return groups;
}

/**
 * Get the property name from a token ID (last segment)
 */
function getPropertyName(tokenId: string): string {
	const parts = tokenId.split('.');
	return parts[parts.length - 1];
}

/**
 * Convert to PascalCase
 */
function toPascalCase(str: string): string {
	return str
		.split(/[-_]/)
		.map((word) => word.charAt(0).toUpperCase() + word.slice(1).toLowerCase())
		.join('');
}

/**
 * Capitalize first letter
 */
function capitalize(str: string): string {
	return str.charAt(0).toUpperCase() + str.slice(1);
}

/**
 * Convert token value to Kotlin literal
 */
function toKotlinValue(token: ResolvedToken): string {
	const category = token.id.split('.')[0];
	const value = token.resolvedValue;

	// Colors
	if (category === 'color' || isHexColor(value)) {
		return `Color(0x${toArgbHex(String(value))})`;
	}

	// Numbers with units
	if (typeof value === 'string') {
		// Pixel values → dp
		if (value.endsWith('px')) {
			return `${Number.parseFloat(value)}.dp`;
		}
		// Rem values → dp (assume 16px base)
		if (value.endsWith('rem')) {
			return `${Number.parseFloat(value) * 16}.dp`;
		}
		// SP values for fonts
		if (value.endsWith('sp')) {
			return `${Number.parseFloat(value)}.sp`;
		}
		// Pure numbers (assume dp for spacing)
		if (/^-?\d+(\.\d+)?$/.test(value)) {
			// Check if it's likely a font size based on token name
			if (token.id.includes('font') || token.id.includes('text')) {
				return `${value}.sp`;
			}
			return `${value}.dp`;
		}
	}

	// Numbers
	if (typeof value === 'number') {
		return `${value}.dp`;
	}

	// Strings
	return `"${escapeKotlinString(String(value))}"`;
}

const KOTLIN_ESCAPES: Record<string, string> = {
	'\\': '\\\\',
	'"': '\\"',
	$: '\\$',
	'\n': '\\n',
	'\r': '\\r',
	'\t': '\\t',
};

/**
 * Escape a value for a double-quoted Kotlin string literal, including `$`
 * so it cannot start a string template
 */
function escapeKotlinString(str: string): string {
	return str.replace(/[\\"$\n\r\t]/g, (c) => KOTLIN_ESCAPES[c]);
}

/**
 * Convert a CSS hex color (#RGB, #RRGGBB or #RRGGBBAA) to the AARRGGBB digits
 * a Color(0x...) literal takes: CSS puts alpha last, the literal puts it first
 */
function toArgbHex(value: string): string {
	const hex = value.replace('#', '').toUpperCase();
	if (hex.length === 8) {
		return hex.slice(6) + hex.slice(0, 6);
	}
	// Expand 3-digit hex to 6 digits
	const rgb =
		hex.length === 3
			? hex
					.split('')
					.map((c) => c + c)
					.join('')
			: hex;
	return `FF${rgb}`;
}

/**
 * Check if value is a hex color
 */
function isHexColor(value: unknown): boolean {
	if (typeof value !== 'string') return false;
	return /^#([0-9A-Fa-f]{3}|[0-9A-Fa-f]{6}|[0-9A-Fa-f]{8})$/.test(value);
}
