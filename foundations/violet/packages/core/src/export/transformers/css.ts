import type { ResolvedToken } from '../../types/token.js';
import type { TransformOptions, Transformer } from '../transformer.js';
import { groupByCategory, tokenIdToKebab } from '../transformer.js';

/**
 * CSS Transformer
 *
 * Exports tokens as CSS custom properties.
 */
export const cssTransformer: Transformer = {
	format: 'css',
	fileExtension: 'css',
	name: 'CSS Custom Properties',

	transform(tokens: ResolvedToken[], options: TransformOptions = {}): string {
		const {
			prefix = '',
			selector = ':root',
			includeComments = false,
			groupByCategory: group = false,
			outputReferences = false,
		} = options;

		const prefixPart = prefix ? `${prefix}-` : '';
		const varNameOf = (tokenId: string) => `--${prefixPart}${tokenIdToKebab(tokenId)}`;
		// Only point at variables this export defines; otherwise use the value.
		const exported = new Set(tokens.map((token) => token.id));
		const cssValue = (token: ResolvedToken) =>
			outputReferences && token.aliasOf && exported.has(token.aliasOf)
				? `var(${varNameOf(token.aliasOf)})`
				: formatCssValue(token.resolvedValue);

		const lines: string[] = [];

		// Add header comment
		lines.push('/* Generated by Violet Design */');
		lines.push('');

		if (group) {
			// Group tokens by category
			const groups = groupByCategory(tokens);
			const sortedCategories = Array.from(groups.keys()).sort();

			lines.push(`${selector} {`);

			for (const category of sortedCategories) {
				const categoryTokens = groups.get(category)!;

				if (includeComments) {
					lines.push(`  /* ${capitalize(category)} */`);
				}

				for (const token of categoryTokens) {
					const varName = varNameOf(token.id);
					const value = cssValue(token);

					if (includeComments && token.metadata?.description) {
						lines.push(`  /* ${token.metadata.description} */`);
					}

					lines.push(`  ${varName}: ${value};`);
				}

				lines.push('');
			}

			// Remove trailing empty line before closing brace
			if (lines[lines.length - 1] === '') {
				lines.pop();
			}

			lines.push('}');
		} else {
			// Flat list
			lines.push(`${selector} {`);

			for (const token of tokens) {
				const varName = varNameOf(token.id);
				const value = cssValue(token);

				if (includeComments && token.metadata?.description) {
					lines.push(`  /* ${token.metadata.description} */`);
				}

				lines.push(`  ${varName}: ${value};`);
			}

			lines.push('}');
		}

		return lines.join('\n');
	},
};

/**
 * Format a token value for CSS
 */
function formatCssValue(value: unknown): string {
	if (typeof value === 'string') {
		return value;
	}
	if (typeof value === 'number') {
		return String(value);
	}
	// For complex values, stringify
	return JSON.stringify(value);
}

/**
 * Capitalize first letter
 */
function capitalize(str: string): string {
	return str.charAt(0).toUpperCase() + str.slice(1);
}
