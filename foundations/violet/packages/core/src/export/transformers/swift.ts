import type { ResolvedToken } from '../../types/token.js';
import type { TransformOptions, Transformer } from '../transformer.js';
import { groupByCategory } from '../transformer.js';

/**
 * Swift Transformer
 *
 * Exports tokens as Swift constants compatible with SwiftUI.
 */
export const swiftTransformer: Transformer = {
	format: 'swift',
	fileExtension: 'swift',
	name: 'Swift (SwiftUI)',

	transform(tokens: ResolvedToken[], options: TransformOptions = {}): string {
		const { prefix = '', includeComments = true } = options;

		// Use className from options or default
		const className = (options as SwiftOptions).className || 'VioletTokens';
		const accessLevel = (options as SwiftOptions).accessLevel || 'public';

		const lines: string[] = [];

		// Header
		lines.push(`// ${className}.swift`);
		lines.push('// Generated by Violet Design');
		lines.push('// Do not edit manually');
		lines.push(`// Generated: ${new Date().toISOString()}`);
		lines.push('');
		lines.push('import SwiftUI');
		lines.push('');
		lines.push(`${accessLevel} struct ${prefix}${className} {`);

		// Group tokens by category
		const groups = groupByCategory(tokens);

		for (const [category, categoryTokens] of groups) {
			lines.push('');
			lines.push(`    // MARK: - ${capitalize(category)}`);
			lines.push('');
			lines.push(`    ${accessLevel} struct ${capitalize(category)} {`);

			// Group by subcategory (second segment)
			const subGroups = groupBySubcategory(categoryTokens);

			for (const [subcategory, subTokens] of subGroups) {
				if (subcategory !== '_root') {
					lines.push(`        ${accessLevel} struct ${capitalize(subcategory)} {`);
				}

				for (const token of subTokens) {
					const swiftValue = toSwiftValue(token);
					const propName = getPropertyName(token.id);
					const indent = subcategory !== '_root' ? '            ' : '        ';

					if (includeComments && token.metadata?.description) {
						lines.push(`${indent}/// ${token.metadata.description}`);
					}

					lines.push(`${indent}${accessLevel} static let ${propName} = ${swiftValue}`);
				}

				if (subcategory !== '_root') {
					lines.push('        }');
				}
			}

			lines.push('    }');
		}

		lines.push('}');
		lines.push('');

		// Add Color extension for hex parsing
		lines.push(SWIFT_COLOR_EXTENSION);

		return lines.join('\n');
	},
};

/**
 * Swift-specific options
 */
interface SwiftOptions extends TransformOptions {
	className?: string;
	accessLevel?: 'public' | 'internal' | 'private';
}

/**
 * Group tokens by subcategory (second segment of ID)
 */
function groupBySubcategory(tokens: ResolvedToken[]): Map<string, ResolvedToken[]> {
	const groups = new Map<string, ResolvedToken[]>();

	for (const token of tokens) {
		const parts = token.id.split('.');
		const subcategory = parts.length > 2 ? parts[1] : '_root';

		if (!groups.has(subcategory)) {
			groups.set(subcategory, []);
		}
		groups.get(subcategory)?.push(token);
	}

	return groups;
}

/**
 * Get the property name from a token ID (last segment, camelCase)
 */
function getPropertyName(tokenId: string): string {
	const parts = tokenId.split('.');
	const name = parts[parts.length - 1];
	return toCamelCase(name);
}

/**
 * Convert to camelCase
 */
function toCamelCase(str: string): string {
	return str
		.split(/[-_]/)
		.map((word, i) =>
			i === 0 ? word.toLowerCase() : word.charAt(0).toUpperCase() + word.slice(1).toLowerCase(),
		)
		.join('');
}

/**
 * Capitalize first letter
 */
function capitalize(str: string): string {
	return str.charAt(0).toUpperCase() + str.slice(1);
}

/**
 * Convert token value to Swift literal
 */
function toSwiftValue(token: ResolvedToken): string {
	const category = token.id.split('.')[0];
	const value = token.resolvedValue;

	// Colors
	if (category === 'color' || isHexColor(value)) {
		return `SwiftUI.Color(hex: "${value}")`;
	}

	// Numbers with units
	if (typeof value === 'string') {
		// Pixel values → CGFloat
		if (value.endsWith('px')) {
			return `CGFloat(${Number.parseFloat(value)})`;
		}
		// Rem values → CGFloat (assume 16px base)
		if (value.endsWith('rem')) {
			return `CGFloat(${Number.parseFloat(value) * 16})`;
		}
		// Em values → CGFloat
		if (value.endsWith('em')) {
			return `CGFloat(${Number.parseFloat(value) * 16})`;
		}
		// Pure numbers
		if (/^-?\d+(\.\d+)?$/.test(value)) {
			return `CGFloat(${value})`;
		}
	}

	// Numbers
	if (typeof value === 'number') {
		return `CGFloat(${value})`;
	}

	// Strings
	return `"${value}"`;
}

/**
 * Check if value is a hex color
 */
function isHexColor(value: unknown): boolean {
	if (typeof value !== 'string') return false;
	return /^#([0-9A-Fa-f]{3}|[0-9A-Fa-f]{6}|[0-9A-Fa-f]{8})$/.test(value);
}

/**
 * Swift Color extension for hex parsing
 */
const SWIFT_COLOR_EXTENSION = `// MARK: - Color Extension

extension SwiftUI.Color {
    init(hex: String) {
        let hex = hex.trimmingCharacters(in: CharacterSet.alphanumerics.inverted)
        var int: UInt64 = 0
        Scanner(string: hex).scanHexInt64(&int)
        let a, r, g, b: UInt64
        switch hex.count {
        case 3: // RGB (12-bit)
            (a, r, g, b) = (255, (int >> 8) * 17, (int >> 4 & 0xF) * 17, (int & 0xF) * 17)
        case 6: // RGB (24-bit)
            (a, r, g, b) = (255, int >> 16, int >> 8 & 0xFF, int & 0xFF)
        case 8: // ARGB (32-bit)
            (a, r, g, b) = (int >> 24, int >> 16 & 0xFF, int >> 8 & 0xFF, int & 0xFF)
        default:
            (a, r, g, b) = (255, 0, 0, 0)
        }
        self.init(
            .sRGB,
            red: Double(r) / 255,
            green: Double(g) / 255,
            blue: Double(b) / 255,
            opacity: Double(a) / 255
        )
    }
}`;
