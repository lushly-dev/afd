import type { ResolvedToken } from '../../types/token.js';
import type { TransformOptions, Transformer } from '../transformer.js';
import { groupByCategory } from '../transformer.js';

/**
 * Dart Transformer
 *
 * Exports tokens as Dart constants for Flutter.
 */
export const dartTransformer: Transformer = {
	format: 'dart',
	fileExtension: 'dart',
	name: 'Dart (Flutter)',

	transform(tokens: ResolvedToken[], options: TransformOptions = {}): string {
		const { includeComments = true } = options;

		// Use dart-specific options
		const className = (options as DartOptions).className || 'VioletTokens';

		const lines: string[] = [];

		// Header
		lines.push(`// ${toSnakeCase(className)}.dart`);
		lines.push('// Generated by Violet Design');
		lines.push('// Do not edit manually');
		lines.push(`// Generated: ${new Date().toISOString()}`);
		lines.push('');
		lines.push("import 'package:flutter/material.dart';");
		lines.push('');
		lines.push(`class ${className} {`);
		lines.push(`  ${className}._();`);

		// Group tokens by category
		const groups = groupByCategory(tokens);

		for (const [category, categoryTokens] of groups) {
			lines.push('');

			if (includeComments) {
				lines.push(`  // ${capitalize(category)}`);
			}

			for (const token of categoryTokens) {
				const dartValue = toDartValue(token);
				const constName = toCamelCase(token.id);
				const dartType = getDartType(token);

				if (includeComments && token.metadata?.description) {
					lines.push(`  /// ${token.metadata.description}`);
				}

				lines.push(`  static const ${dartType} ${constName} = ${dartValue};`);
			}
		}

		lines.push('}');

		return lines.join('\n');
	},
};

/**
 * Dart-specific options
 */
interface DartOptions extends TransformOptions {
	className?: string;
}

/**
 * Convert token ID to camelCase
 */
function toCamelCase(tokenId: string): string {
	const parts = tokenId.split('.');
	return parts
		.map((part, i) => {
			const words = part.split(/[-_]/);
			return words
				.map((word, j) =>
					i === 0 && j === 0
						? word.toLowerCase()
						: word.charAt(0).toUpperCase() + word.slice(1).toLowerCase(),
				)
				.join('');
		})
		.join('');
}

/**
 * Convert to snake_case
 */
function toSnakeCase(str: string): string {
	return str
		.replace(/([A-Z])/g, '_$1')
		.toLowerCase()
		.replace(/^_/, '');
}

/**
 * Capitalize first letter
 */
function capitalize(str: string): string {
	return str.charAt(0).toUpperCase() + str.slice(1);
}

/**
 * Get Dart type for a token
 */
function getDartType(token: ResolvedToken): string {
	const category = token.id.split('.')[0];
	const value = token.resolvedValue;

	if (category === 'color' || isHexColor(value)) {
		return 'Color';
	}

	if (typeof value === 'number') {
		return 'double';
	}

	if (typeof value === 'string') {
		if (value.endsWith('px') || value.endsWith('rem') || value.endsWith('em')) {
			return 'double';
		}
		if (/^-?\d+(\.\d+)?$/.test(value)) {
			return 'double';
		}
	}

	return 'String';
}

/**
 * Convert token value to Dart literal
 */
function toDartValue(token: ResolvedToken): string {
	const category = token.id.split('.')[0];
	const value = token.resolvedValue;

	// Colors
	if (category === 'color' || isHexColor(value)) {
		return `Color(0x${toArgbHex(String(value))})`;
	}

	// Numbers with units
	if (typeof value === 'string') {
		// Pixel values → double
		if (value.endsWith('px')) {
			return `${Number.parseFloat(value)}.0`;
		}
		// Rem values → double (assume 16px base)
		if (value.endsWith('rem')) {
			return `${Number.parseFloat(value) * 16}.0`;
		}
		// Em values → double
		if (value.endsWith('em')) {
			return `${Number.parseFloat(value) * 16}.0`;
		}
		// Pure numbers
		if (/^-?\d+(\.\d+)?$/.test(value)) {
			const num = Number.parseFloat(value);
			return Number.isInteger(num) ? `${num}.0` : `${num}`;
		}
	}

	// Numbers
	if (typeof value === 'number') {
		return Number.isInteger(value) ? `${value}.0` : `${value}`;
	}

	// Strings
	return `'${escapeDartString(String(value))}'`;
}

const DART_ESCAPES: Record<string, string> = {
	'\\': '\\\\',
	"'": "\\'",
	$: '\\$',
	'\n': '\\n',
	'\r': '\\r',
	'\t': '\\t',
};

/**
 * Escape a value for a single-quoted Dart string literal, including `$`
 * so it cannot start a string interpolation
 */
function escapeDartString(str: string): string {
	return str.replace(/[\\'$\n\r\t]/g, (c) => DART_ESCAPES[c]);
}

/**
 * Convert a CSS hex color (#RGB, #RRGGBB or #RRGGBBAA) to the AARRGGBB digits
 * a Color(0x...) literal takes: CSS puts alpha last, the literal puts it first
 */
function toArgbHex(value: string): string {
	const hex = value.replace('#', '').toUpperCase();
	if (hex.length === 8) {
		return hex.slice(6) + hex.slice(0, 6);
	}
	// Expand 3-digit hex to 6 digits
	const rgb =
		hex.length === 3
			? hex
					.split('')
					.map((c) => c + c)
					.join('')
			: hex;
	return `FF${rgb}`;
}

/**
 * Check if value is a hex color
 */
function isHexColor(value: unknown): boolean {
	if (typeof value !== 'string') return false;
	return /^#([0-9A-Fa-f]{3}|[0-9A-Fa-f]{6}|[0-9A-Fa-f]{8})$/.test(value);
}
