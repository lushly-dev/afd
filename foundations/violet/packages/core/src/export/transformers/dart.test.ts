import { describe, expect, it } from 'vitest';
import type { ResolvedToken } from '../../types/token.js';
import { dartTransformer } from './dart.js';

const token = (id: string, value: string | number, description?: string): ResolvedToken => ({
	id,
	value,
	resolvedValue: value,
	metadata: {
		category: 'custom',
		tier: 'semantic',
		status: 'stable',
		platforms: [],
		tags: [],
		...(description ? { description } : {}),
	},
	resolvedAt: 'test',
	inheritanceChain: ['test'],
});

const declarationOf = (dart: string, name: string) =>
	dart
		.split('\n')
		.find((line) => line.includes(` ${name} = `))
		?.trim();

describe('dart transformer', () => {
	it('emits a private-constructor Flutter class named after className', () => {
		const dart = dartTransformer.transform([token('color.primary', '#0078D4')], {
			className: 'BrandTokens',
		});

		expect(dart).toMatch(/^\/\/ brand_tokens\.dart\n\/\/ Generated by Violet Design\n/);
		expect(dart).toContain("import 'package:flutter/material.dart';");
		expect(dart).toContain('class BrandTokens {\n  BrandTokens._();');
		expect(dart.endsWith('}')).toBe(true);
	});

	it('defaults to VioletTokens in violet_tokens.dart', () => {
		const dart = dartTransformer.transform([]);

		expect(dart).toContain('// violet_tokens.dart');
		expect(dart).toContain('class VioletTokens {\n  VioletTokens._();\n}');
	});

	it('names constants in camelCase across segments, kebab and snake parts', () => {
		const dart = dartTransformer.transform([
			token('color.brand-accent.primary', '#0078D4'),
			token('spacing.stack_gap', 4),
		]);

		expect(dart).toContain('static const Color colorBrandAccentPrimary = Color(0xFF0078D4);');
		expect(dart).toContain('static const double spacingStackGap = 4.0;');
	});

	it('emits colors, expanding three-digit hex, for the color category and hex values', () => {
		const dart = dartTransformer.transform([
			token('color.short', '#fa0'),
			token('border.focus', '#abcdef'),
		]);

		expect(declarationOf(dart, 'colorShort')).toBe(
			'static const Color colorShort = Color(0xFFFFAA00);',
		);
		expect(declarationOf(dart, 'borderFocus')).toBe(
			'static const Color borderFocus = Color(0xFFABCDEF);',
		);
	});

	it('moves the alpha of eight-digit CSS hex to the front of the ARGB literal', () => {
		const dart = dartTransformer.transform([
			token('color.gold-overlay', '#FFD70080'),
			token('color.scrim', '#00000033'),
		]);

		expect(declarationOf(dart, 'colorGoldOverlay')).toBe(
			'static const Color colorGoldOverlay = Color(0x80FFD700);',
		);
		expect(declarationOf(dart, 'colorScrim')).toBe(
			'static const Color colorScrim = Color(0x33000000);',
		);
	});

	it('converts dimensions to doubles with a 16px base for rem and em', () => {
		const dart = dartTransformer.transform([
			token('spacing.px', '12px'),
			token('spacing.rem', '1.5rem'),
			token('spacing.em', '0.5em'),
			token('spacing.bare', '8'),
			token('spacing.fraction', '0.25'),
			token('spacing.int', 4),
			token('opacity.half', 0.5),
		]);

		expect(declarationOf(dart, 'spacingPx')).toBe('static const double spacingPx = 12.0;');
		expect(declarationOf(dart, 'spacingRem')).toBe('static const double spacingRem = 24.0;');
		expect(declarationOf(dart, 'spacingEm')).toBe('static const double spacingEm = 8.0;');
		expect(declarationOf(dart, 'spacingBare')).toBe('static const double spacingBare = 8.0;');
		expect(declarationOf(dart, 'spacingFraction')).toBe(
			'static const double spacingFraction = 0.25;',
		);
		expect(declarationOf(dart, 'spacingInt')).toBe('static const double spacingInt = 4.0;');
		expect(declarationOf(dart, 'opacityHalf')).toBe('static const double opacityHalf = 0.5;');
	});

	it('emits other values as Strings', () => {
		const dart = dartTransformer.transform([token('motion.easing', 'ease-in-out')]);

		expect(declarationOf(dart, 'motionEasing')).toBe(
			"static const String motionEasing = 'ease-in-out';",
		);
	});

	it('escapes quotes, backslashes, interpolation dollars and control characters in strings', () => {
		const dart = dartTransformer.transform([
			token('font.family', `"Segoe UI", 'Helvetica Neue', sans-serif`),
			token('content.path', 'icons\\$name'),
			token('content.lines', 'one\ntwo'),
		]);

		expect(declarationOf(dart, 'fontFamily')).toBe(
			`static const String fontFamily = '"Segoe UI", \\'Helvetica Neue\\', sans-serif';`,
		);
		expect(declarationOf(dart, 'contentPath')).toBe(
			"static const String contentPath = 'icons\\\\\\$name';",
		);
		expect(declarationOf(dart, 'contentLines')).toBe(
			"static const String contentLines = 'one\\ntwo';",
		);
	});

	it('writes category headings and doc comments unless includeComments is false', () => {
		const tokens = [token('spacing.md', 16, 'Default gap'), token('spacing.lg', 24)];

		const withComments = dartTransformer.transform(tokens);
		expect(withComments).toContain(
			'  // Spacing\n  /// Default gap\n  static const double spacingMd = 16.0;\n  static const double spacingLg = 24.0;',
		);

		const without = dartTransformer.transform(tokens, { includeComments: false });
		expect(without).not.toContain('// Spacing');
		expect(without).not.toContain('Default gap');
	});
});
