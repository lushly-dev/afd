import { mkdtempSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import typescript from 'typescript';
import { describe, expect, it } from 'vitest';
import type { ResolvedToken } from '../../types/token.js';
import { typescriptTransformer } from './typescript.js';

const token = (id: string, resolvedValue: unknown, description?: string): ResolvedToken =>
	({
		id,
		value: resolvedValue,
		resolvedValue,
		metadata: {
			category: 'custom',
			tier: 'semantic',
			status: 'stable',
			platforms: [],
			tags: [],
			...(description ? { description } : {}),
		},
		resolvedAt: 'test',
		inheritanceChain: ['test'],
	}) as ResolvedToken;

const tokens = [token('color.brand.primary', '#0078D4', 'Brand colour'), token('spacing.md', 16)];

const HEADER = '/**\n * Generated by Violet Design\n * Do not edit manually\n */\n';

/** Type-check generated files with the workspace compiler and return its diagnostics. */
function typeCheck(files: Map<string, string>): string[] {
	const dir = mkdtempSync(join(tmpdir(), 'violet-ts-export-'));
	try {
		for (const [name, content] of files) {
			writeFileSync(join(dir, name), content);
		}
		const program = typescript.createProgram(
			Array.from(files.keys(), (name) => join(dir, name)),
			{
				strict: true,
				noEmit: true,
				skipLibCheck: true,
				target: typescript.ScriptTarget.ES2022,
				module: typescript.ModuleKind.ESNext,
				moduleResolution: typescript.ModuleResolutionKind.Bundler,
				lib: ['lib.es2022.d.ts'],
				types: [],
			},
		);
		return typescript
			.getPreEmitDiagnostics(program)
			.map((d) => `TS${d.code}: ${typescript.flattenDiagnosticMessageText(d.messageText, '\n')}`);
	} finally {
		rmSync(dir, { recursive: true, force: true });
	}
}

describe('typescript transformer', () => {
	it('emits named constants and a nested `tokens` object by default', () => {
		expect(typescriptTransformer.transform(tokens)).toBe(
			[
				HEADER,
				"export const colorBrandPrimary = '#0078D4';",
				'export const spacingMd = 16;',
				'',
				'export const tokens = {',
				'  color: {',
				'    brand: {',
				"      primary: '#0078D4'",
				'    }',
				'  },',
				'  spacing: {',
				'    md: 16',
				'  }',
				'} as const;',
			].join('\n'),
		);
	});

	it('emits the nested object as the default export for exportType default', () => {
		const ts = typescriptTransformer.transform(tokens, { exportType: 'default' });

		expect(ts).toContain('export default {\n  color: {');
		expect(ts).toContain('} as const;');
		expect(ts).not.toContain('export const colorBrandPrimary');
		expect(ts).not.toContain('export const tokens');
	});

	it('emits only named constants for exportStyle flat with exportType named', () => {
		const ts = typescriptTransformer.transform(tokens, {
			exportStyle: 'flat',
			exportType: 'named',
		});

		expect(ts).toContain('export const spacingMd = 16;');
		expect(ts).not.toContain('export const tokens');
		expect(ts).not.toContain('export default');
	});

	it('emits only named constants for exportStyle flat with the default exportType', () => {
		const ts = typescriptTransformer.transform(tokens, { exportStyle: 'flat' });

		expect(ts).toBe(
			[
				HEADER,
				"export const colorBrandPrimary = '#0078D4';",
				'export const spacingMd = 16;',
				'',
			].join('\n'),
		);
	});

	it('keeps the named constants beside the default export for exportStyle flat', () => {
		const ts = typescriptTransformer.transform(tokens, {
			exportStyle: 'flat',
			exportType: 'default',
		});

		expect(ts).toContain('export const spacingMd = 16;');
		expect(ts).toContain('export default {\n  color: {');
		expect(ts).not.toContain('export const tokens');
	});

	it('prefixes the named constants', () => {
		const ts = typescriptTransformer.transform(tokens, { prefix: 'vlt_', exportType: 'named' });

		expect(ts).toContain("export const vlt_colorBrandPrimary = '#0078D4';");
	});

	it('adds section comments and JSDoc descriptions with includeComments', () => {
		const ts = typescriptTransformer.transform(tokens, { includeComments: true });

		expect(ts).toContain('// Named exports for direct access');
		expect(ts).toContain("/** Brand colour */\nexport const colorBrandPrimary = '#0078D4';");
		expect(ts).toContain('// Nested token object\nexport const tokens = {');
		expect(ts).not.toContain('/** undefined */');
	});

	it('escapes quotes, backslashes and newlines in string values', () => {
		const ts = typescriptTransformer.transform([token('font.family', "It's \\ a\nfont")], {
			exportStyle: 'flat',
			exportType: 'named',
		});

		expect(ts).toContain("export const fontFamily = 'It\\'s \\\\ a\\nfont';");
	});

	it('formats composite, array, boolean and null values as literals', () => {
		const ts = typescriptTransformer.transform(
			[
				token('typography.body', { fontFamily: 'Segoe UI', 'font-size': 14, weights: [400, 600] }),
				token('flag.enabled', true),
				token('flag.unset', null),
				token('font.stack', ['Segoe UI', 'sans-serif']),
			],
			{ exportType: 'named' },
		);

		expect(ts).toContain(
			"export const typographyBody = {\n  fontFamily: 'Segoe UI',\n  'font-size': 14,\n  weights: [400, 600]\n};",
		);
		expect(ts).toContain('export const flagEnabled = true;');
		expect(ts).toContain('export const flagUnset = null;');
		expect(ts).toContain("export const fontStack = ['Segoe UI', 'sans-serif'];");
	});

	it('quotes nested keys that are not identifiers', () => {
		const ts = typescriptTransformer.transform([token('spacing.2xl', 32)], {
			exportType: 'default',
		});

		expect(ts).toContain("  spacing: {\n    '2xl': 32\n  }");
	});

	describe('transformMulti', () => {
		it('writes one file per category plus an index re-exporting them', () => {
			const files = typescriptTransformer.transformMulti?.(tokens);

			expect(Array.from(files?.keys() ?? [])).toEqual(['color.ts', 'spacing.ts', 'index.ts']);
			expect(files?.get('color.ts')).toContain("export const colorBrandPrimary = '#0078D4';");
			expect(files?.get('color.ts')).not.toContain('spacingMd');
			expect(files?.get('spacing.ts')).toContain('export const spacingMd = 16;');
			expect(files?.get('index.ts')).toBe(
				[
					HEADER,
					"export * from './color.js';",
					"export * from './spacing.js';",
					'',
					"import { tokens as tokens0 } from './color.js';",
					"import { tokens as tokens1 } from './spacing.js';",
					'',
					'export const tokens = { ...tokens0, ...tokens1 } as const;',
				].join('\n'),
			);
		});

		it('generates files that type-check together for several categories', () => {
			const files = typescriptTransformer.transformMulti?.([
				...tokens,
				token('radius.sm', '2px'),
				token('font.family.body', '"Segoe UI", sans-serif'),
			]);

			expect(files?.size).toBe(5);
			expect(typeCheck(files ?? new Map())).toEqual([]);
		});

		it('merges every category into the index tokens object', () => {
			const files = typescriptTransformer.transformMulti?.(tokens) ?? new Map<string, string>();
			const index = `${files.get('index.ts')}\nconst primary: '#0078D4' = tokens.color.brand.primary;\nconst md: 16 = tokens.spacing.md;\nexport { md, primary };`;

			expect(typeCheck(new Map([...files, ['index.ts', index]]))).toEqual([]);
		});

		it('writes no tokens object for exportStyle flat, and still type-checks', () => {
			const files = typescriptTransformer.transformMulti?.(tokens, { exportStyle: 'flat' });

			expect(files?.get('color.ts')).not.toContain('tokens');
			expect(files?.get('index.ts')).toBe(
				`${HEADER}\nexport * from './color.js';\nexport * from './spacing.js';`,
			);
			expect(typeCheck(files ?? new Map())).toEqual([]);
		});

		it('passes the caller options to every category file', () => {
			const files = typescriptTransformer.transformMulti?.(tokens, { includeComments: true });

			expect(files?.get('color.ts')).toContain('/** Brand colour */');
		});
	});
});
