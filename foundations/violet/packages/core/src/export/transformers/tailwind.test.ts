import { describe, expect, it } from 'vitest';
import type { ResolvedToken } from '../../types/token.js';
import { tailwindTransformer } from './tailwind.js';

const token = (id: string, value: string | number): ResolvedToken => ({
	id,
	value,
	resolvedValue: value,
	metadata: { category: 'custom', tier: 'semantic', status: 'stable', platforms: [], tags: [] },
	resolvedAt: 'test',
	inheritanceChain: ['test'],
});

/** Evaluate the generated CommonJS config and return its theme.extend. */
function extendOf(source: string): Record<string, Record<string, unknown>> {
	const module = {
		exports: {} as { theme?: { extend?: Record<string, Record<string, unknown>> } },
	};
	new Function('module', source)(module);
	return module.exports.theme?.extend ?? {};
}

describe('tailwind transformer', () => {
	it('emits a CommonJS config with a timestamped header by default', () => {
		const js = tailwindTransformer.transform([token('color.primary', '#0078D4')]);

		expect(js).toMatch(/^\/\/ tailwind\.config\.js\n\/\/ Generated by Violet Design\n/);
		expect(js).toMatch(/\/\/ Generated: \d{4}-\d{2}-\d{2}T/);
		expect(js).toContain("/** @type {import('tailwindcss').Config} */\nmodule.exports = {");
		expect(js).not.toContain('export default');
	});

	it('emits an ES module with esm', () => {
		const js = tailwindTransformer.transform([token('color.primary', '#0078D4')], { esm: true });

		expect(js).toContain('export default {\n  theme: {\n    extend: {');
		expect(js).not.toContain('module.exports');
	});

	it('nests colors below the category and keeps their values', () => {
		const extend = extendOf(
			tailwindTransformer.transform([
				token('color.brand.primary', '#0078D4'),
				token('color.brand.secondary', '#107C10'),
				token('color.white', '#fff'),
			]),
		);

		expect(extend.colors).toEqual({
			brand: { primary: '#0078D4', secondary: '#107C10' },
			white: '#fff',
		});
	});

	it('maps spacing, shadow and opacity to flat scales with px for bare numbers', () => {
		const extend = extendOf(
			tailwindTransformer.transform([
				token('spacing.sm', 4),
				token('spacing.md', '1rem'),
				token('spacing.lg', '24px'),
				token('spacing.gutter', 'clamp(1rem, 2vw, 2rem)'),
				token('spacing.inset.card', -8),
				token('shadow.card', '0 2px 4px rgba(0, 0, 0, 0.2)'),
				token('opacity.disabled', 0.4),
			]),
		);

		expect(extend.spacing).toEqual({
			sm: '4px',
			md: '1rem',
			lg: '24px',
			gutter: 'clamp(1rem, 2vw, 2rem)',
			'inset-card': '-8px',
		});
		expect(extend.boxShadow).toEqual({ card: '0 2px 4px rgba(0, 0, 0, 0.2)' });
		expect(extend.opacity).toEqual({ disabled: '0.4' });
	});

	it('normalises radius values from either radius category', () => {
		const radius = extendOf(
			tailwindTransformer.transform([
				token('radius.sm', 2),
				token('radius.md', '0.5rem'),
				token('radius.full', '9999px'),
				token('radius.pill', '50%'),
			]),
		);
		const borderRadius = extendOf(tailwindTransformer.transform([token('borderRadius.lg', 12)]));

		expect(radius.borderRadius).toEqual({ sm: '2px', md: '0.5rem', full: '9999px', pill: '50%' });
		expect(borderRadius.borderRadius).toEqual({ lg: '12px' });
	});

	it('merges the radius and borderRadius categories into one scale', () => {
		const extend = extendOf(
			tailwindTransformer.transform([
				token('radius.sm', 2),
				token('borderRadius.lg', 12),
				token('radius.md', '0.5rem'),
			]),
		);

		expect(extend.borderRadius).toEqual({ sm: '2px', md: '0.5rem', lg: '12px' });
	});

	it('sorts font and typography tokens into size, family, weight and line-height scales', () => {
		const extend = extendOf(
			tailwindTransformer.transform([
				token('font.size.sm', 12),
				token('font.size.md', '1rem'),
				token('font.size.lg', '20px'),
				token('font.size.fluid', 'clamp(1rem, 2vw, 2rem)'),
				token('font.family.body', '"Segoe UI", system-ui, sans-serif'),
				token('font.weight.bold', 700),
				token('typography.line-height.tight', 1.2),
				token('typography.lineHeight.loose', '2rem'),
				token('font.letter-spacing', '0.01em'),
			]),
		);

		expect(extend.fontSize).toEqual({
			'size-sm': '12px',
			'size-md': '1rem',
			'size-lg': '20px',
			'size-fluid': 'clamp(1rem, 2vw, 2rem)',
		});
		expect(extend.fontFamily).toEqual({ 'family-body': ['Segoe UI', 'system-ui', 'sans-serif'] });
		expect(extend.fontWeight).toEqual({ 'weight-bold': '700' });
		expect(extend.lineHeight).toEqual({ 'line-height-tight': '1.2', 'lineHeight-loose': '2rem' });
		// Tokens that match no font scale are not exported.
		expect(JSON.stringify(extend)).not.toContain('letter-spacing');
	});

	it('omits unknown categories and empty scales', () => {
		const extend = extendOf(
			tailwindTransformer.transform([token('motion.fast', '100ms'), token('spacing.sm', 4)]),
		);

		expect(Object.keys(extend)).toEqual(['spacing']);
	});

	it('emits an empty extend object when nothing maps', () => {
		const js = tailwindTransformer.transform([token('motion.fast', '100ms')]);

		expect(js).toContain('    extend: {},');
		expect(extendOf(js)).toEqual({});
	});

	it('drops tokens with unsafe path segments instead of polluting prototypes', () => {
		const js = tailwindTransformer.transform([
			token('color.__proto__.polluted', 'red'),
			token('spacing.constructor', 4),
			token('color.ok', 'blue'),
		]);
		const extend = extendOf(js);

		expect(extend.colors).toEqual({ ok: 'blue' });
		expect(extend).not.toHaveProperty('spacing');
		expect(({} as Record<string, unknown>).polluted).toBeUndefined();
	});

	it('quotes keys that are not identifiers', () => {
		const js = tailwindTransformer.transform([token('spacing.2xl', 32)]);

		expect(js).toContain("'2xl': '32px',");
	});
});
