import type { ResolvedToken } from '../../types/token.js';
import type { TransformOptions, Transformer } from '../transformer.js';
import { groupByCategory, tokenIdToKebab } from '../transformer.js';

/**
 * SCSS Transformer
 *
 * Exports tokens as SCSS variables.
 */
export const scssTransformer: Transformer = {
	format: 'scss',
	fileExtension: 'scss',
	name: 'SCSS Variables',

	transform(tokens: ResolvedToken[], options: TransformOptions = {}): string {
		const { prefix = '', includeComments = false, groupByCategory: group = false } = options;

		const lines: string[] = [];

		// Add header comment
		lines.push('// Generated by Violet Design');
		lines.push('');

		if (group) {
			// Group tokens by category
			const groups = groupByCategory(tokens);
			const sortedCategories = Array.from(groups.keys()).sort();

			for (const category of sortedCategories) {
				const categoryTokens = groups.get(category)!;

				lines.push(`// ${capitalize(category)}`);

				for (const token of categoryTokens) {
					const varName = `$${prefix}${tokenIdToKebab(token.id)}`;
					const value = formatScssValue(token.resolvedValue);

					if (includeComments && token.metadata?.description) {
						lines.push(`// ${token.metadata.description}`);
					}

					lines.push(`${varName}: ${value};`);
				}

				lines.push('');
			}
		} else {
			// Flat list
			for (const token of tokens) {
				const varName = `$${prefix}${tokenIdToKebab(token.id)}`;
				const value = formatScssValue(token.resolvedValue);

				if (includeComments && token.metadata?.description) {
					lines.push(`// ${token.metadata.description}`);
				}

				lines.push(`${varName}: ${value};`);
			}
		}

		return lines.join('\n');
	},
};

/**
 * Format a token value for SCSS
 */
function formatScssValue(value: unknown): string {
	if (typeof value === 'string') {
		return value;
	}
	if (typeof value === 'number') {
		return String(value);
	}
	// For complex values, use SCSS maps
	if (typeof value === 'object' && value !== null) {
		return formatScssMap(value as Record<string, unknown>);
	}
	return String(value);
}

/**
 * Format an object as SCSS map
 */
function formatScssMap(obj: Record<string, unknown>): string {
	const entries = Object.entries(obj).map(([key, val]) => {
		const formattedVal =
			typeof val === 'object' && val !== null
				? formatScssMap(val as Record<string, unknown>)
				: formatScssValue(val);
		return `"${key}": ${formattedVal}`;
	});

	return `(${entries.join(', ')})`;
}

/**
 * Capitalize first letter
 */
function capitalize(str: string): string {
	return str.charAt(0).toUpperCase() + str.slice(1);
}
