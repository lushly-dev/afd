import { describe, expect, it } from 'vitest';
import type { ResolvedToken } from '../../types/token.js';
import { swiftTransformer } from './swift.js';

const token = (id: string, value: string | number, description?: string): ResolvedToken => ({
	id,
	value,
	resolvedValue: value,
	metadata: {
		category: 'custom',
		tier: 'semantic',
		status: 'stable',
		platforms: [],
		tags: [],
		...(description ? { description } : {}),
	},
	resolvedAt: 'test',
	inheritanceChain: ['test'],
});

const lineFor = (swift: string, name: string) =>
	swift
		.split('\n')
		.find((line) => line.includes(` static let ${name} =`))
		?.trim();

describe('swift transformer', () => {
	it('wraps tokens in a public VioletTokens struct with the hex Color extension', () => {
		const swift = swiftTransformer.transform([token('color.primary', '#0078D4')]);

		expect(swift).toMatch(/^\/\/ VioletTokens\.swift\n\/\/ Generated by Violet Design\n/);
		expect(swift).toContain('import SwiftUI\n\npublic struct VioletTokens {');
		expect(swift).toContain('extension SwiftUI.Color {\n    init(hex: String) {');
	});

	it('applies className, prefix and accessLevel to every declaration', () => {
		const swift = swiftTransformer.transform([token('spacing.md', 16)], {
			className: 'Brand',
			prefix: 'XB',
			accessLevel: 'internal',
		});

		expect(swift).toContain('// Brand.swift');
		expect(swift).toContain('internal struct XBBrand {');
		expect(swift).toContain('    internal struct Spacing {');
		expect(swift).toContain('        internal static let md = CGFloat(16)');
		expect(swift).not.toContain('public ');
	});

	it('nests a struct per category and per subcategory', () => {
		const swift = swiftTransformer.transform([
			token('color.brand.primary', '#0078D4'),
			token('color.white', '#fff'),
			token('spacing.md', 16),
		]);

		expect(swift).toContain(
			'    public struct Color {\n        public struct Brand {\n            public static let primary = SwiftUI.Color(hex: "#0078D4")\n        }\n        public static let white = SwiftUI.Color(hex: "#fff")\n    }',
		);
		expect(swift).toContain('    // MARK: - Spacing\n\n    public struct Spacing {');
	});

	it('converts dimensions to CGFloat with a 16px base for rem and em', () => {
		const swift = swiftTransformer.transform([
			token('spacing.px', '12px'),
			token('spacing.rem', '1.5rem'),
			token('spacing.em', '0.5em'),
			token('spacing.bare', '-4'),
			token('spacing.number', 8),
		]);

		expect(lineFor(swift, 'px')).toBe('public static let px = CGFloat(12)');
		expect(lineFor(swift, 'rem')).toBe('public static let rem = CGFloat(24)');
		expect(lineFor(swift, 'em')).toBe('public static let em = CGFloat(8)');
		expect(lineFor(swift, 'bare')).toBe('public static let bare = CGFloat(-4)');
		expect(lineFor(swift, 'number')).toBe('public static let number = CGFloat(8)');
	});

	it('treats hex values outside the color category as colors and other strings as strings', () => {
		const swift = swiftTransformer.transform([
			token('border.focus', '#FFF'),
			token('motion.easing', 'ease-in-out'),
			token('font.family', 'Segoe UI'),
		]);

		expect(lineFor(swift, 'focus')).toBe('public static let focus = SwiftUI.Color(hex: "#FFF")');
		expect(lineFor(swift, 'easing')).toBe('public static let easing = "ease-in-out"');
		expect(lineFor(swift, 'family')).toBe('public static let family = "Segoe UI"');
	});

	it('camel-cases kebab and snake property names', () => {
		const swift = swiftTransformer.transform([
			token('spacing.inset.card-padding', 4),
			token('spacing.stack_gap', 2),
		]);

		expect(swift).toContain('public static let cardPadding = CGFloat(4)');
		expect(swift).toContain('public static let stackGap = CGFloat(2)');
	});

	it('emits descriptions as doc comments unless includeComments is false', () => {
		const tokens = [token('spacing.md', 16, 'Default gap')];

		expect(swiftTransformer.transform(tokens)).toContain(
			'        /// Default gap\n        public static let md = CGFloat(16)',
		);
		expect(swiftTransformer.transform(tokens, { includeComments: false })).not.toContain(
			'Default gap',
		);
	});
});
