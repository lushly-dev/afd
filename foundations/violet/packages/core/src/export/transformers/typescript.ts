/**
 * Sanitize a string into a safe JS/TS identifier and avoid reserved keywords
 */
function sanitizeIdentifier(str: string): string {
	let cleaned = str.replace(/[^a-zA-Z0-9_$]/g, '_');
	if (!cleaned || /^\d/.test(cleaned) || JS_RESERVED.has(cleaned)) {
		cleaned = `_${cleaned}`;
	}
	return cleaned;
}

/**
 * Allocate a unique identifier within a scope
 */
function allocateUniqueIdentifier(raw: string, used: Set<string>): string {
	const base = sanitizeIdentifier(raw);
	let candidate = base;
	let suffix = 2;
	while (used.has(candidate)) {
		candidate = `${base}_${suffix++}`;
	}
	used.add(candidate);
	return candidate;
}

/**
 * Sanitize a category name into a safe, case-insensitively unique file basename for transformMulti
 */
function uniqueFileBase(category: string, usedLower: Set<string>): string {
	let base = category.replace(/[^a-zA-Z0-9_-]/g, '_');
	const lower = base.toLowerCase();
	if (!base || lower === 'index' || WINDOWS_RESERVED_FILENAMES.has(lower) || /^\.+$/.test(base)) {
		base = `_${base || 'tokens'}`;
	}
	let candidate = base;
	let suffix = 2;
	while (usedLower.has(candidate.toLowerCase())) {
		candidate = `${base}_${suffix++}`;
	}
	usedLower.add(candidate.toLowerCase());
	return candidate;
}

/**
 * Neutralize block comment terminators and line breaks inside single-line JSDoc
 */
function sanitizeBlockComment(str: string): string {
	return str.replace(/\*\//g, '*\\/').replace(/[\r\n]+/g, ' ');
}

/**
 * Escape special characters in a string
 */
function escapeString(str: string): string {
	return str
		.replace(/\\/g, '\\\\')
		.replace(/'/g, "\\'")
		.replace(/\n/g, '\\n')
		.replace(/\r/g, '\\r')
		.replaceAll('\0', '\\x00')
		.replace(/\u2028/g, '\\u2028')
		.replace(/\u2029/g, '\\u2029');
}
