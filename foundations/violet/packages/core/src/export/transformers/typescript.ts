import type { ResolvedToken } from '../../types/token.js';
import type { TransformOptions, Transformer } from '../transformer.js';
import { groupByCategory, tokenIdToCamel, tokensToNestedObject } from '../transformer.js';

/**
 * TypeScript Transformer
 *
 * Exports tokens as TypeScript constants.
 */
export const typescriptTransformer: Transformer = {
	format: 'typescript',
	fileExtension: 'ts',
	name: 'TypeScript Constants',

	transform(tokens: ResolvedToken[], options: TransformOptions = {}): string {
		const {
			prefix = '',
			exportStyle = 'nested',
			exportType = 'both',
			includeComments = false,
		} = options;

		const lines: string[] = [];

		// Add header comment
		lines.push('/**');
		lines.push(' * Generated by Violet Design');
		lines.push(' * Do not edit manually');
		lines.push(' */');
		lines.push('');

		if (exportStyle === 'flat' || exportType === 'named' || exportType === 'both') {
			// Generate named exports for flat access
			if (includeComments) {
				lines.push('// Named exports for direct access');
			}

			for (const token of tokens) {
				const constName = prefix + tokenIdToCamel(token.id);
				const value = formatTsValue(token.resolvedValue);

				if (includeComments && token.metadata?.description) {
					lines.push(`/** ${token.metadata.description} */`);
				}

				lines.push(`export const ${constName} = ${value};`);
			}

			lines.push('');
		}

		if (exportStyle === 'nested' || exportType === 'default' || exportType === 'both') {
			// Generate nested object export
			if (includeComments) {
				lines.push('// Nested token object');
			}

			const nested = tokensToNestedObject(tokens);
			const nestedStr = formatNestedObject(nested, 0);

			if (exportType === 'default') {
				lines.push(`export default ${nestedStr} as const;`);
			} else {
				lines.push(`export const tokens = ${nestedStr} as const;`);
			}
		}

		return lines.join('\n');
	},

	transformMulti(tokens: ResolvedToken[], options: TransformOptions = {}): Map<string, string> {
		const files = new Map<string, string>();
		const groups = groupByCategory(tokens);
		const indexExports: string[] = [];

		// Generate file per category
		for (const [category, categoryTokens] of groups) {
			const content = this.transform(categoryTokens, {
				...options,
				exportType: 'named', // Per-category files use named exports
			});
			files.set(`${category}.ts`, content);
			indexExports.push(`export * from './${category}.js';`);
		}

		// Generate index file
		const indexLines = [
			'/**',
			' * Generated by Violet Design',
			' * Do not edit manually',
			' */',
			'',
			...indexExports,
		];
		files.set('index.ts', indexLines.join('\n'));

		return files;
	},
};

/**
 * Format a value for TypeScript
 */
function formatTsValue(value: unknown): string {
	if (typeof value === 'string') {
		return `'${escapeString(value)}'`;
	}
	if (typeof value === 'number' || typeof value === 'boolean') {
		return String(value);
	}
	if (value === null) {
		return 'null';
	}
	if (Array.isArray(value)) {
		const items = value.map((v) => formatTsValue(v)).join(', ');
		return `[${items}]`;
	}
	if (typeof value === 'object') {
		return formatNestedObject(value as Record<string, unknown>, 0);
	}
	return String(value);
}

/**
 * Format a nested object with proper indentation
 */
function formatNestedObject(obj: Record<string, unknown>, depth: number): string {
	const indent = '  '.repeat(depth);
	const innerIndent = '  '.repeat(depth + 1);

	const entries = Object.entries(obj).map(([key, val]) => {
		const formattedKey = isValidIdentifier(key) ? key : `'${key}'`;
		const formattedVal =
			typeof val === 'object' && val !== null && !Array.isArray(val)
				? formatNestedObject(val as Record<string, unknown>, depth + 1)
				: formatTsValue(val);
		return `${innerIndent}${formattedKey}: ${formattedVal}`;
	});

	return `{\n${entries.join(',\n')}\n${indent}}`;
}

/**
 * Check if a string is a valid JS identifier
 */
function isValidIdentifier(str: string): boolean {
	return /^[a-zA-Z_$][a-zA-Z0-9_$]*$/.test(str);
}

/**
 * Escape special characters in a string
 */
function escapeString(str: string): string {
	return str.replace(/\\/g, '\\\\').replace(/'/g, "\\'").replace(/\n/g, '\\n');
}
