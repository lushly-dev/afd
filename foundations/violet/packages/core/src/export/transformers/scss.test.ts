import { describe, expect, it } from 'vitest';
import type { ResolvedToken } from '../../types/token.js';
import { scssTransformer } from './scss.js';

const token = (id: string, resolvedValue: unknown, description?: string): ResolvedToken =>
	({
		id,
		value: resolvedValue,
		resolvedValue,
		metadata: {
			category: 'custom',
			tier: 'semantic',
			status: 'stable',
			platforms: [],
			tags: [],
			...(description ? { description } : {}),
		},
		resolvedAt: 'test',
		inheritanceChain: ['test'],
	}) as ResolvedToken;

const tokens = [
	token('spacing.md', 16, 'Default gap'),
	token('color.brand.primary', '#0078D4', 'Brand colour'),
	token('color.brand.secondary', '#107C10'),
];

describe('scss transformer', () => {
	it('emits flat SCSS variables in token order', () => {
		expect(scssTransformer.transform(tokens)).toBe(
			[
				'// Generated by Violet Design',
				'',
				'$spacing-md: 16;',
				'$color-brand-primary: #0078D4;',
				'$color-brand-secondary: #107C10;',
			].join('\n'),
		);
	});

	it('prepends the prefix verbatim to each variable name', () => {
		const scss = scssTransformer.transform(tokens, { prefix: 'vlt-' });

		expect(scss).toContain('$vlt-color-brand-primary: #0078D4;');
		expect(scss).toContain('$vlt-spacing-md: 16;');
	});

	it('writes descriptions as comments only when asked', () => {
		expect(scssTransformer.transform(tokens)).not.toContain('Brand colour');
		expect(scssTransformer.transform(tokens, { includeComments: true })).toContain(
			'// Brand colour\n$color-brand-primary: #0078D4;',
		);
	});

	it('groups by sorted category under a heading, with descriptions on request', () => {
		const scss = scssTransformer.transform(tokens, {
			groupByCategory: true,
			includeComments: true,
		});

		expect(scss).toBe(
			[
				'// Generated by Violet Design',
				'',
				'// Color',
				'// Brand colour',
				'$color-brand-primary: #0078D4;',
				'$color-brand-secondary: #107C10;',
				'',
				'// Spacing',
				'// Default gap',
				'$spacing-md: 16;',
				'',
			].join('\n'),
		);
	});

	it('omits descriptions in grouped output without includeComments', () => {
		const scss = scssTransformer.transform(tokens, { groupByCategory: true });

		expect(scss).toContain('// Color\n$color-brand-primary');
		expect(scss).not.toContain('Brand colour');
	});

	it('renders composite values as nested SCSS maps', () => {
		const scss = scssTransformer.transform([
			token('typography.body', {
				fontFamily: 'Segoe UI',
				fontSize: 14,
				lineHeight: { value: 1.5, unit: null },
			}),
		]);

		expect(scss).toContain(
			'$typography-body: ("fontFamily": Segoe UI, "fontSize": 14, "lineHeight": ("value": 1.5, "unit": null));',
		);
	});

	it('stringifies other primitive values', () => {
		expect(scssTransformer.transform([token('flag.enabled', true)])).toContain(
			'$flag-enabled: true;',
		);
	});
});
