import { describe, expect, it } from 'vitest';
import type { ResolvedToken } from '../../types/token.js';
import { cssTransformer } from './css.js';

const token = (
	id: string,
	value: string | number,
	extra: { description?: string; aliasOf?: string; resolvedValue?: unknown } = {},
): ResolvedToken =>
	({
		id,
		value,
		resolvedValue: extra.resolvedValue ?? value,
		...(extra.aliasOf ? { aliasOf: extra.aliasOf } : {}),
		metadata: {
			category: 'custom',
			tier: 'semantic',
			status: 'stable',
			platforms: [],
			tags: [],
			...(extra.description ? { description: extra.description } : {}),
		},
		resolvedAt: 'test',
		inheritanceChain: ['test'],
	}) as ResolvedToken;

const tokens = [
	token('spacing.md', 16, { description: 'Default gap' }),
	token('color.brand.primary', '#0078D4', { description: 'Brand colour' }),
	token('color.text.link', '#0078D4', { aliasOf: 'color.brand.primary' }),
];

describe('css transformer', () => {
	it('emits a flat :root block in token order', () => {
		const css = cssTransformer.transform(tokens);

		expect(css).toBe(
			[
				'/* Generated by Violet Design */',
				'',
				':root {',
				'  --spacing-md: 16;',
				'  --color-brand-primary: #0078D4;',
				'  --color-text-link: #0078D4;',
				'}',
			].join('\n'),
		);
	});

	it('applies prefix and selector', () => {
		const css = cssTransformer.transform(tokens, {
			prefix: 'vlt',
			selector: '[data-theme="dark"]',
		});

		expect(css).toContain('[data-theme="dark"] {');
		expect(css).toContain('  --vlt-color-brand-primary: #0078D4;');
		expect(css).not.toContain(':root');
	});

	it('writes descriptions as comments only when asked', () => {
		expect(cssTransformer.transform(tokens)).not.toContain('Brand colour');

		const css = cssTransformer.transform(tokens, { includeComments: true });
		expect(css).toContain('  /* Brand colour */\n  --color-brand-primary: #0078D4;');
		expect(css).toContain('  /* Default gap */\n  --spacing-md: 16;');
	});

	it('serialises composite values as JSON', () => {
		const css = cssTransformer.transform([
			token('shadow.card', 0, { resolvedValue: { x: 0, y: 2, blur: 4 } }),
		]);

		expect(css).toContain('  --shadow-card: {"x":0,"y":2,"blur":4};');
	});

	describe('outputReferences', () => {
		it('emits aliases as var() of the exported target, with the prefix', () => {
			const css = cssTransformer.transform(tokens, { outputReferences: true, prefix: 'vlt' });

			expect(css).toContain('  --vlt-color-text-link: var(--vlt-color-brand-primary);');
			expect(css).toContain('  --vlt-color-brand-primary: #0078D4;');
		});

		it('falls back to the value when the alias target is not part of the export', () => {
			const css = cssTransformer.transform([tokens[2]], { outputReferences: true });

			expect(css).toContain('  --color-text-link: #0078D4;');
			expect(css).not.toContain('var(');
		});
	});

	describe('groupByCategory', () => {
		it('sorts categories and separates them with a blank line, without a trailing one', () => {
			const css = cssTransformer.transform(tokens, { groupByCategory: true });

			expect(css).toBe(
				[
					'/* Generated by Violet Design */',
					'',
					':root {',
					'  --color-brand-primary: #0078D4;',
					'  --color-text-link: #0078D4;',
					'',
					'  --spacing-md: 16;',
					'}',
				].join('\n'),
			);
		});

		it('adds category headings and descriptions with includeComments', () => {
			const css = cssTransformer.transform(tokens, {
				groupByCategory: true,
				includeComments: true,
				outputReferences: true,
			});

			expect(css).toContain(
				'  /* Color */\n  /* Brand colour */\n  --color-brand-primary: #0078D4;\n  --color-text-link: var(--color-brand-primary);',
			);
			expect(css).toContain('  /* Spacing */\n  /* Default gap */\n  --spacing-md: 16;\n}');
		});

		it('emits an empty block for no tokens', () => {
			expect(cssTransformer.transform([], { groupByCategory: true })).toBe(
				'/* Generated by Violet Design */\n\n:root {\n}',
			);
		});
	});
});
