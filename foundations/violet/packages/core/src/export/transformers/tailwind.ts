import { findUnsafeTokenIdSegment } from '../../types/token-id.js';
import type { ResolvedToken } from '../../types/token.js';
import type { TransformOptions, Transformer } from '../transformer.js';
import { buildNestedTokenObject, groupByCategory } from '../transformer.js';

/**
 * Tailwind CSS Transformer
 *
 * Exports tokens as Tailwind CSS configuration.
 */
export const tailwindTransformer: Transformer = {
	format: 'tailwind',
	fileExtension: 'js',
	name: 'Tailwind CSS Config',

	transform(tokens: ResolvedToken[], options: TransformOptions = {}): string {
		// Use tailwind-specific options
		const esm = (options as TailwindOptions).esm ?? false;

		const lines: string[] = [];

		// Header
		lines.push('// tailwind.config.js');
		lines.push('// Generated by Violet Design');
		lines.push('// Do not edit manually');
		lines.push(`// Generated: ${new Date().toISOString()}`);
		lines.push('');

		// Build theme extend object
		const themeExtend = buildThemeExtend(tokens);
		const themeStr = formatObject(themeExtend, 2);

		lines.push("/** @type {import('tailwindcss').Config} */");

		if (esm) {
			lines.push('export default {');
		} else {
			lines.push('module.exports = {');
		}

		lines.push('  theme: {');
		lines.push(`    extend: ${themeStr},`);
		lines.push('  },');
		lines.push('};');

		return lines.join('\n');
	},
};

/**
 * Tailwind-specific options
 */
interface TailwindOptions extends TransformOptions {
	esm?: boolean;
}

/**
 * Build Tailwind theme.extend object from tokens
 */
function buildThemeExtend(tokens: ResolvedToken[]): Record<string, unknown> {
	const dict = (): Record<string, unknown> => Object.create(null);
	const theme: Record<string, Record<string, unknown>> = {
		colors: dict(),
		spacing: dict(),
		fontSize: dict(),
		fontFamily: dict(),
		fontWeight: dict(),
		lineHeight: dict(),
		borderRadius: dict(),
		boxShadow: dict(),
		opacity: dict(),
	};

	// Group tokens by category, dropping ids with unsafe path segments
	const groups = groupByCategory(tokens.filter((t) => findUnsafeTokenIdSegment(t.id) === null));

	for (const [category, categoryTokens] of groups) {
		switch (category) {
			case 'color':
				theme.colors = buildNestedObject(categoryTokens, toTailwindColor);
				break;

			case 'spacing':
				theme.spacing = buildFlatObject(categoryTokens, toTailwindSpacing);
				break;

			case 'font':
			case 'typography':
				for (const token of categoryTokens) {
					const key = getShortName(token.id);
					const value = token.resolvedValue;

					if (token.id.includes('size')) {
						theme.fontSize[key] = toTailwindFontSize(value);
					} else if (token.id.includes('family')) {
						theme.fontFamily[key] = toTailwindFontFamily(value);
					} else if (token.id.includes('weight')) {
						theme.fontWeight[key] = String(value);
					} else if (token.id.includes('line-height') || token.id.includes('lineHeight')) {
						theme.lineHeight[key] = toTailwindLineHeight(value);
					}
				}
				break;

			case 'radius':
			case 'borderRadius':
				// Both categories feed one scale; on a shared key the later category wins
				Object.assign(theme.borderRadius, buildFlatObject(categoryTokens, toTailwindRadius));
				break;

			case 'shadow':
				theme.boxShadow = buildFlatObject(categoryTokens, (v) => String(v));
				break;

			case 'opacity':
				theme.opacity = buildFlatObject(categoryTokens, (v) => String(v));
				break;

			default:
				// Skip unknown categories
				break;
		}
	}

	// Remove empty categories
	const result: Record<string, unknown> = {};
	for (const [key, value] of Object.entries(theme)) {
		if (Object.keys(value).length > 0) {
			result[key] = value;
		}
	}

	return result;
}

/**
 * Build a nested object from tokens (for colors)
 *
 * Unsafe path segments are skipped and leaf/group collisions are resolved
 * deterministically (group wins) by buildNestedTokenObject.
 */
function buildNestedObject(
	tokens: ResolvedToken[],
	valueFn: (value: unknown) => string,
): Record<string, unknown> {
	return buildNestedTokenObject(
		tokens,
		(token) => valueFn(token.resolvedValue),
		(token) => token.id.split('.').slice(1), // Remove category
	);
}

/**
 * Build a flat object from tokens
 */
function buildFlatObject(
	tokens: ResolvedToken[],
	valueFn: (value: unknown) => string,
): Record<string, string> {
	const result: Record<string, string> = Object.create(null);

	for (const token of tokens) {
		if (findUnsafeTokenIdSegment(token.id) !== null) {
			continue;
		}
		const key = getShortName(token.id);
		result[key] = valueFn(token.resolvedValue);
	}

	return result;
}

/**
 * Get short name from token ID (last segment or last two if nested)
 */
function getShortName(tokenId: string): string {
	const parts = tokenId.split('.');
	if (parts.length <= 2) {
		return parts[parts.length - 1];
	}
	// Use last two segments for more specific names
	return parts.slice(-2).join('-');
}

/**
 * Convert color value to Tailwind format
 */
function toTailwindColor(value: unknown): string {
	return String(value);
}

/**
 * Convert spacing value to Tailwind format
 */
function toTailwindSpacing(value: unknown): string {
	const str = String(value);
	// Keep px values as-is for Tailwind
	if (str.endsWith('px')) {
		return str;
	}
	// Convert rem to rem string
	if (str.endsWith('rem')) {
		return str;
	}
	// Pure numbers → px
	if (/^-?\d+(\.\d+)?$/.test(str)) {
		return `${str}px`;
	}
	return str;
}

/**
 * Convert font size value to Tailwind format
 */
function toTailwindFontSize(value: unknown): string {
	const str = String(value);
	if (str.endsWith('px') || str.endsWith('rem')) {
		return str;
	}
	if (/^-?\d+(\.\d+)?$/.test(str)) {
		return `${str}px`;
	}
	return str;
}

/**
 * Convert font family value to Tailwind format
 */
function toTailwindFontFamily(value: unknown): string[] {
	const str = String(value);
	// Split by comma for font stacks
	return str.split(',').map((f) => f.trim().replace(/['"]/g, ''));
}

/**
 * Convert line height value to Tailwind format
 */
function toTailwindLineHeight(value: unknown): string {
	const str = String(value);
	// Unitless line heights are preferred in Tailwind
	if (/^\d+(\.\d+)?$/.test(str)) {
		return str;
	}
	return str;
}

/**
 * Convert border radius value to Tailwind format
 */
function toTailwindRadius(value: unknown): string {
	const str = String(value);
	if (str.endsWith('px') || str.endsWith('rem')) {
		return str;
	}
	if (/^-?\d+(\.\d+)?$/.test(str)) {
		return `${str}px`;
	}
	return str;
}

/**
 * Format object as JavaScript string with proper indentation
 */
function formatObject(obj: Record<string, unknown>, baseIndent: number): string {
	const indent = '  '.repeat(baseIndent);
	const innerIndent = '  '.repeat(baseIndent + 1);

	const entries = Object.entries(obj);
	if (entries.length === 0) {
		return '{}';
	}

	const lines: string[] = ['{'];

	for (const [key, value] of entries) {
		const formattedKey = /^[a-zA-Z_$][a-zA-Z0-9_$]*$/.test(key) ? key : `'${key}'`;

		if (value && typeof value === 'object' && !Array.isArray(value)) {
			const nestedStr = formatObject(value as Record<string, unknown>, baseIndent + 1);
			lines.push(`${innerIndent}${formattedKey}: ${nestedStr},`);
		} else if (Array.isArray(value)) {
			const arrayStr = JSON.stringify(value);
			lines.push(`${innerIndent}${formattedKey}: ${arrayStr},`);
		} else {
			lines.push(`${innerIndent}${formattedKey}: '${value}',`);
		}
	}

	lines.push(`${indent}}`);
	return lines.join('\n');
}
