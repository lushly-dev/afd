/**
 * The incumbent's representative path (T04): each consumer's own Storybook Vitest config, run
 * over the story files for the components the native wrappers mount. A generated wrapper config
 * loads that config unchanged and adds one plugin, which points the test page's Google Fonts
 * links at the recorded-font server. Nothing in the frozen snapshot is edited.
 */
import { spawn } from 'node:child_process';
import { readFile, rm, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { performance } from 'node:perf_hooks';

export const incumbents = {
	'fast-af': {
		config: 'vitest.config.ts',
		args: ['--project', 'storybook'],
		files: [
			'packages/violet-elements/src/button/violet-button.stories.ts',
			'packages/violet-elements/src/text-field/violet-text-field.stories.ts',
			'packages/violet-elements/src/alert/violet-alert.stories.ts',
			'packages/violet-elements/src/theme/violet-theme.stories.ts',
		],
	},
	lushly: {
		config: 'vitest.storybook.config.ts',
		args: [],
		files: [
			'apps/web/src/components/shared/lushly-empty-state/lushly-empty-state.stories.ts',
			'apps/web/src/components/shared/lushly-tier-badge/lushly-tier-badge.stories.ts',
			'apps/web/src/components/shared/lushly-view-tabs/lushly-view-tabs.stories.ts',
			'apps/web/src/components/shell/lushly-section-frame/lushly-section-frame.stories.ts',
		],
	},
};

/** The policy's incumbent cold condition: the snapshot's Storybook and Vite caches removed. */
export const coldCaches = ['node_modules/.cache/storybook', 'node_modules/.vite'];

export async function writeWrapperConfig({ snapshot, consumer, directory }) {
	const descriptor = incumbents[consumer];
	const file = join(directory, `vitest.${consumer}.incumbent.config.mjs`);
	const rewrite = new URL('./inputs/font-rewrite.mjs', import.meta.url).href;
	await writeFile(
		file,
		`// Generated by experiments/incumbent.mjs; loads the consumer's config unchanged.
import base from ${JSON.stringify(join(snapshot, descriptor.config))};
import { readFileSync } from 'node:fs';
import { rewriteHtml } from ${JSON.stringify(rewrite)};
const record = JSON.parse(readFileSync(process.env.SPECIMEN_FONT_RECORD, 'utf8'));
const fonts = {
	name: 'specimen-recorded-fonts',
	enforce: 'post',
	transformIndexHtml: (html) => rewriteHtml(html, record, process.env.SPECIMEN_FONT_BASE),
};
const config = typeof base === 'function' ? await base({ mode: 'test', command: 'serve' }) : base;
config.plugins = [...(config.plugins ?? []), fonts];
export default config;
`
	);
	return file;
}

/** One `vitest run` of the selection; `cold` removes the caches first. */
export async function runIncumbent({ snapshot, consumer, wrapper, kind, report, fonts, env = {} }) {
	const descriptor = incumbents[consumer];
	if (kind === 'cold')
		for (const cache of coldCaches)
			await rm(join(snapshot, cache), { recursive: true, force: true });
	const args = [
		'run',
		'--config',
		wrapper,
		'--root',
		snapshot,
		...descriptor.args,
		'--reporter=json',
		`--outputFile=${report}`,
		...descriptor.files,
	];
	const start = performance.now();
	const child = spawn(join(snapshot, 'node_modules/.bin/vitest'), args, {
		cwd: snapshot,
		env: {
			...process.env,
			...env,
			SPECIMEN_FONT_RECORD: fonts.record,
			SPECIMEN_FONT_BASE: fonts.base,
		},
		stdio: ['ignore', 'pipe', 'pipe'],
	});
	let output = '';
	child.stdout.on('data', (chunk) => {
		output += chunk;
	});
	child.stderr.on('data', (chunk) => {
		output += chunk;
	});
	const code = await new Promise((resolveExit) => child.on('close', resolveExit));
	const elapsedMs = performance.now() - start;
	let results = null;
	try {
		results = JSON.parse(await readFile(report, 'utf8'));
	} catch {
		// Reported below as a failed run.
	}
	return {
		kind,
		code,
		elapsedMs,
		passed: results?.numPassedTests ?? null,
		failed: results?.numFailedTests ?? null,
		total: results?.numTotalTests ?? null,
		files: results?.numTotalTestSuites ?? null,
		output: code === 0 ? undefined : output.slice(-4000),
	};
}
