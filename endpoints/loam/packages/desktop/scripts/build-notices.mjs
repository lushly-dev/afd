#!/usr/bin/env node
/**
 * Writes the installers' third-party notices into `dist-notices/` (#2808): `THIRD_PARTY_NOTICES.txt` (`notices.mjs`
 * says what it covers), `RUST_STANDARD_LIBRARY_NOTICES.html` (the pinned toolchain's own `COPYRIGHT-library.html`,
 * for the standard library compiled into the app), and `tauri.notices.json`, the `--config` that `build-installers`
 * passes `tauri build` to bundle both as resources beside the app on every target.
 *
 * Expects `@lushly-dev/loam-web` and `@lushly-dev/loam-copilot` built (their module records) and the crate's
 * dependencies fetched; any gap stops it.
 */
import { spawnSync } from 'node:child_process';
import {
	copyFileSync,
	existsSync,
	mkdirSync,
	readFileSync,
	realpathSync,
	rmSync,
	writeFileSync,
} from 'node:fs';
import { join, sep } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import {
	DESKTOP_TARGETS,
	dedupePackages,
	findPackage,
	npmPackages,
	readModuleRecord,
	renderNotices,
	resolveNotices,
	rustCrates,
} from './notices.mjs';

const PACKAGE = fileURLToPath(new URL('..', import.meta.url));
const SRC_TAURI = join(PACKAGE, 'src-tauri');
const REPO = fileURLToPath(new URL('../../../../..', import.meta.url));
export const NOTICES_DIR = join(PACKAGE, 'dist-notices');
export const NOTICES_FILE = 'THIRD_PARTY_NOTICES.txt';
export const STD_NOTICES_FILE = 'RUST_STANDARD_LIBRARY_NOTICES.html';
export const TAURI_CONFIG = join(NOTICES_DIR, 'tauri.notices.json');

/** Each build's module record, and a file its build always holds, so an empty or broken record is refused. */
const RECORDS = [
	{
		file: join(PACKAGE, '../web/build-record/modules.json'),
		build: '@lushly-dev/loam-web',
		entry: join(PACKAGE, '../web/src/main.ts'),
	},
	{
		file: join(PACKAGE, '../copilot/dist/frame/modules.json'),
		build: '@lushly-dev/loam-copilot',
		entry: join(PACKAGE, '../copilot/src/frame/bootstrap.ts'),
	},
];

function run(command, args) {
	const result = spawnSync(command, args, {
		cwd: SRC_TAURI,
		encoding: 'utf8',
		maxBuffer: 512 * 1024 * 1024,
	});
	if (result.error) throw new Error(`${command}: ${result.error.message}`);
	if (result.status !== 0) {
		throw new Error(`${command} ${args.join(' ')} exited ${result.status}:\n${result.stderr}`);
	}
	return result.stdout;
}

export function buildNotices() {
	const out = NOTICES_DIR;
	const conf = JSON.parse(readFileSync(join(SRC_TAURI, 'tauri.conf.json'), 'utf8'));
	const records = RECORDS.map(({ file, build, entry }) => {
		if (!existsSync(file)) {
			throw new Error(`${file} is missing: build ${build} first (pnpm -F "${build}..." build)`);
		}
		const record = readModuleRecord(file);
		const want = realpathSync(entry).split(sep).join('/').toLowerCase();
		if (!record.modules?.some((id) => id.toLowerCase() === want)) {
			throw new Error(
				`${file} does not hold ${entry}, which every ${build} build does: rebuild it, or fix its module record (#2808)`
			);
		}
		return record;
	});
	// The polyfill the binary embeds (`src-tauri/build.rs`), whether or not the shell's bundle holds it too.
	const polyfill = findPackage('@webcomponents/scoped-custom-element-registry', PACKAGE);

	const metadata = JSON.parse(
		run('cargo', [
			'metadata',
			'--locked',
			'--format-version',
			'1',
			...DESKTOP_TARGETS.flatMap((target) => ['--filter-platform', target]),
		])
	);
	const rustc = run('rustc', ['--version']).trim();
	const sysroot = run('rustc', ['--print', 'sysroot']).trim();
	const stdNotices = join(sysroot, 'share', 'doc', 'rust', 'COPYRIGHT-library.html');
	if (!existsSync(stdNotices)) {
		throw new Error(`${stdNotices} is missing: the toolchain's standard library notices (#2808)`);
	}

	const crates = resolveNotices(rustCrates(metadata));
	const npm = resolveNotices(
		dedupePackages(npmPackages(records, { repoRoot: REPO, extra: [polyfill] }))
	);
	const text = renderNotices({
		product: conf.productName,
		version: conf.version,
		preamble: [
			`${conf.productName} contains the third-party software listed below. Each entry names the licence its authors declare and, by number, the notice texts at the end of this file: the licence, copying, notice and third-party files its source ships, or, where it ships none, the standard text of each licence it declares. One file serves every platform, so it lists some crates a given platform does not build.`,
			`The Rust standard library, compiled into the app by ${rustc}, is under the MIT licence or the Apache License 2.0; its notices, with those of the code it includes, are in ${STD_NOTICES_FILE} beside this file.`,
			"Generated by endpoints/loam/packages/desktop/scripts/build-notices.mjs from the build's own inputs.",
		],
		sections: [
			{
				title: 'Rust crates compiled into the app on one or more desktop platforms',
				packages: crates,
			},
			{
				title: 'npm packages and repository code in the bundled web shell',
				packages: npm,
			},
		],
	});

	rmSync(out, { recursive: true, force: true });
	mkdirSync(out, { recursive: true });
	writeFileSync(join(out, NOTICES_FILE), text);
	copyFileSync(stdNotices, join(out, STD_NOTICES_FILE));
	// Resource paths are relative to `src-tauri/`; a map puts each file at the top of the app's resources.
	const resources = Object.fromEntries(
		[NOTICES_FILE, STD_NOTICES_FILE].map((name) => [`../dist-notices/${name}`, name])
	);
	writeFileSync(
		join(out, 'tauri.notices.json'),
		`${JSON.stringify({ bundle: { resources } }, null, '\t')}\n`
	);
	return { crates: crates.length, npm: npm.length, bytes: Buffer.byteLength(text) };
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
	const summary = buildNotices();
	console.log(
		`Third-party notices for ${summary.crates} crates and ${summary.npm} npm and repository packages (${summary.bytes} bytes) are in ${NOTICES_DIR}`
	);
}
