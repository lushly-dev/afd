/**
 * The theme's outputs (2.1, 2.3): the contract, `loam-theme.css` and `loam-theme.json`, rendered
 * here rather than by Violet's exporters, which have no exclusion filter and no override diff.
 */
import {
	buildLoamTree,
	type ContractKind,
	type ContractType,
	compactNode,
	contractTypeOf,
	isPrimitive,
	NODE_IDS,
	ROOT_NODE,
	THEMES,
	themeNode,
} from './tree/index.js';

export const CONTRACT_VERSION = 1;

export interface ContractEntry {
	property: string;
	type: ContractType;
	kind: ContractKind;
}

export interface Contract {
	contractVersion: typeof CONTRACT_VERSION;
	tokens: Record<string, ContractEntry>;
}

/** `@lushly-dev/violet-runtime`'s token shape, with the resolved value. */
export interface Token {
	id: string;
	value: string;
}

/** A broken reference, which no output may contain. */
export interface BrokenReference {
	nodeId: string;
	tokenId: string;
	message: string;
}

export interface ResolvedTree {
	/** Per node, every exported token (no `ref.*`) by id, in id order. */
	nodes: Map<string, Map<string, string>>;
	brokenReferences: BrokenReference[];
}

/** `--` + the id with `.` replaced by `-` (`color.surface.page` → `--color-surface-page`). */
export const cssProperty = (id: string): string => `--${id.replaceAll('.', '-')}`;

const byId = (a: string, b: string) => (a < b ? -1 : a > b ? 1 : 0);

export async function resolveTree(): Promise<ResolvedTree> {
	const tree = await buildLoamTree();
	const nodes = new Map<string, Map<string, string>>();
	const brokenReferences: BrokenReference[] = [];
	for (const nodeId of NODE_IDS) {
		const tokens = await tree.resolve(nodeId);
		for (const token of tokens)
			if (token.referenceError)
				brokenReferences.push({ nodeId, tokenId: token.id, message: token.referenceError.message });
		const exported = tokens
			.filter((token) => !isPrimitive(token.id))
			.sort((a, b) => byId(a.id, b.id));
		nodes.set(nodeId, new Map(exported.map((token) => [token.id, String(token.resolvedValue)])));
	}
	return { nodes, brokenReferences };
}

const node = (resolved: ResolvedTree, nodeId: string): Map<string, string> => {
	const tokens = resolved.nodes.get(nodeId);
	if (!tokens) throw new Error(`Node '${nodeId}' is not in the tree`);
	return tokens;
};

export function renderContract(resolved: ResolvedTree): Contract {
	const tokens: Record<string, ContractEntry> = {};
	for (const id of node(resolved, ROOT_NODE).keys())
		tokens[id] = {
			property: cssProperty(id),
			type: contractTypeOf(id),
			kind: id.startsWith('shell.') ? 'shell' : 'component',
		};
	return { contractVersion: CONTRACT_VERSION, tokens };
}

/** The tokens of `nodeId` whose resolved value differs from `baseId`'s. */
function diff(resolved: ResolvedTree, nodeId: string, baseId: string): [string, string][] {
	const base = node(resolved, baseId);
	return [...node(resolved, nodeId)].filter(([id, value]) => base.get(id) !== value);
}

function block(selector: string, tokens: Iterable<[string, string]>): string {
	const lines = [...tokens].map(([id, value]) => `\t${cssProperty(id)}: ${value};`);
	return `${selector} {\n${lines.join('\n')}\n}\n`;
}

const themeSelector = (theme: string) => `[data-loam-theme="${theme}"]`;

export function renderCss(resolved: ResolvedTree): string {
	const light = themeNode('light');
	const blocks = [
		block(`:root,\n${themeSelector('light')}`, node(resolved, light)),
		...THEMES.filter((theme) => theme !== 'light').map((theme) =>
			block(themeSelector(theme), diff(resolved, themeNode(theme), light))
		),
		...THEMES.map((theme) =>
			block(
				`${themeSelector(theme)}[data-loam-density="compact"]`,
				diff(resolved, compactNode(theme), themeNode(theme))
			)
		),
	];
	return [
		"/* Generated by @lushly-dev/loam-theme's theme:build from Loam's Violet tree; do not edit. */\n",
		...blocks,
	].join('\n');
}

export function renderThemeJson(resolved: ResolvedTree): {
	contractVersion: typeof CONTRACT_VERSION;
	nodes: Record<string, Token[]>;
} {
	const nodes: Record<string, Token[]> = {};
	for (const nodeId of NODE_IDS)
		nodes[nodeId] = [...node(resolved, nodeId)].map(([id, value]) => ({ id, value }));
	return { contractVersion: CONTRACT_VERSION, nodes };
}

/** JSON as the repository writes it: tab indentation and a final newline. */
export const toJson = (value: unknown): string => `${JSON.stringify(value, null, '\t')}\n`;

export interface ThemeOutputs {
	resolved: ResolvedTree;
	contract: Contract;
	files: { 'loam-theme.css': string; 'loam-theme.json': string; 'contract.json': string };
}

export async function buildOutputs(): Promise<ThemeOutputs> {
	const resolved = await resolveTree();
	const contract = renderContract(resolved);
	return {
		resolved,
		contract,
		files: {
			'loam-theme.css': renderCss(resolved),
			'loam-theme.json': toJson(renderThemeJson(resolved)),
			'contract.json': toJson(contract),
		},
	};
}
