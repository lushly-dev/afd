def digest(raw: bytes) -> str:
    return hashlib.sha256(raw).hexdigest()


def encode(value) -> bytes:
    return (json.dumps(value, indent=2) + "\n").encode()


def git(repository: Path, *arguments: str) -> bytes:
    return subprocess.check_output(
        ["git", "-C", str(repository), *arguments],
        env={key: value for key, value in os.environ.items() if not key.startswith("GIT_")},
    )


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--upstream-git", required=True, type=Path)
    parser.add_argument("--staged-manifest", required=True, type=Path)
    options = parser.parse_args()
    staged_raw = options.staged_manifest.read_bytes()
    assert digest(staged_raw) == STAGED_MANIFEST_SHA256
    staged = json.loads(staged_raw)
    paths = git(ROOT, "ls-files", "--cached", "--others", "--exclude-standard", "-z", "--", ".")
    candidates = set(paths.decode().strip("\0").split("\0"))
    candidates |= {row["path"] for row in staged["files"]}
    candidates = {
        name
        for name in candidates
        if name and not name.startswith(("provenance/", "src/botcore/provenance/"))
    }
    tree = git(options.upstream_git, "ls-tree", "-r", "-z", REVISION)
    blobs = {}
    for line in tree.decode().strip("\0").split("\0"):
        descriptor, name = line.split("\t", 1)
        mode, kind, blob = descriptor.split()
        if kind == "blob":
            blobs[name] = (mode, blob)
    upstream_files = []
    for name in sorted(candidates & set(blobs)):
        mode, blob = blobs[name]
        raw = git(options.upstream_git, "cat-file", "blob", blob)
        upstream_files.append(
            {
                "path": name,
                "sha256": digest(raw),
                "git_blob": blob,
                "git_mode": mode,
                "selected_in_staged_input": any(row["path"] == name for row in staged["files"]),
            }
        )
    upstream = {
        "kind": "immutable-git-object-baseline",
        "repository": staged["source"],
        "revision": REVISION,
        "git_tree": git(options.upstream_git, "rev-parse", f"{REVISION}^{{tree}}").decode().strip(),
        "selection": "Frozen staged input paths plus reviewed post-stage import references",
        "files": upstream_files,
        "absent_at_revision": sorted(candidates - set(blobs)),
    }
    upstream_raw = encode(upstream)
    upstream_by_path = {row["path"]: row["sha256"] for row in upstream_files}
    staged_by_path = {row["path"]: row["sha256"] for row in staged["files"]}
    rows = []
    for name in sorted(candidates):
        original = upstream_by_path.get(name)
        staged_hash = staged_by_path.get(name)
        file = ROOT / name
        imported = digest(file.read_bytes()) if file.exists() else None
        stage_class, import_class = classify(original, staged_hash, imported)
        stage_reasons = {
            "not-in-staging": "Not selected in the frozen staged-input payload",
            "added-in-staging": "Reviewed staging addition absent from upstream revision",
            "modified-upstream": "Reviewed compatibility adaptation made in temporary staging",
            "unchanged-upstream": "Staged bytes match the immutable upstream Git object",
        }
        import_reasons = {
            "added-after-staging": "Reviewed AFD import support, validation or provenance tooling",
            "modified-after-staging": "Reviewed AFD bootstrap/version, compatibility or CI changes",
            "unchanged-staged": "Imported exact frozen staged-input bytes",
            "deleted-after-staging": "Explicitly excluded during reviewed import",
        }
        if stage_class in {"added-in-staging", "modified-upstream"}:
            stage_reasons[stage_class] = (
                "Copy unchanged upstream root MIT notice into the optional distribution"
                if name.endswith("/LICENSE")
                else STAGE_REASONS[name]
            )
        if import_class in {"added-after-staging", "modified-after-staging"}:
            import_reasons[import_class] = IMPORT_REASONS[name]
        rows.append(
            {
                "path": name,
                "upstream_sha256": original,
                "staged_sha256": staged_hash,
                "current_import_sha256": imported,
                "stage_classification": stage_class,
                "stage_reason": stage_reasons[stage_class],
                "import_classification": import_class,
                "import_reason": import_reasons[import_class],
            }
        )
    adaptations_raw = encode(
        {
            "kind": "reviewed-import-adaptations",
            "source_revision": REVISION,
            "scope": "Reviewed import scope; future edits require explicit adaptation updates",
            "files": rows,
        }
    )
    records = {
        "upstream": ("upstream-selected.json", upstream_raw),
        "staged_input": ("staged-input-allowlist.json", staged_raw),
        "adaptations": ("adaptations.json", adaptations_raw),
    }
    envelope = {
        "schema_version": 2,
        "source_repository": staged["source"],
        "source_revision": REVISION,
        "source_branch_at_selection": "main",
        "records": {
            key: {"manifest": name, "sha256": digest(raw)} for key, (name, raw) in records.items()
        },
        "interpretation": (
            "Only upstream-selected.json describes upstream bytes. The exact frozen staged input "
            "includes adaptations/additions; its revision is context, not upstream hash identity. "
            "adaptations.json records both transitions."
        ),
        "license": "MIT",
        "source_authority": staged["source"],
        "publisher_authority": "original Botcore repository; no handoff authorized",
        "publication_state": "quarantined",
    }
    for directory in (ROOT / "provenance", ROOT / "src/botcore/provenance"):
        directory.mkdir(exist_ok=True)
        for key, (name, raw) in records.items():
            target = directory / name
            if key != "adaptations" and target.exists():
                assert target.read_bytes() == raw, f"Immutable evidence differs: {target}"
            target.write_bytes(raw)
        (directory / "provenance.json").write_bytes(encode(envelope))
        (directory / "source-allowlist.json").unlink(missing_ok=True)
    print(
        json.dumps(
            {
                "upstream_sha256": digest(upstream_raw),
                "staged_sha256": digest(staged_raw),
                "upstream_paths": len(upstream_files),
                "classified_paths": len(rows),
            }
        )
    )


if __name__ == "__main__":
    main()
